#!/usr/bin/env python3
"""Занят ли владелец сетью прямо сейчас — команда вместо памяти вахты.

🔴 ЗАЧЕМ. Ретроспектива 05.09.2026 назвала причину всего дня одной строкой:
**механизм, оптимизированный под отсутствие владельца, был применён при его
присутствии.** `/auto` §0 знает два состояния — работает и не работает.
Третьего, «владелец за машиной и что-то делает в сети», не было, и вахта
две трети дня гнала темп, рассчитанный на пустую комнату.

Правило §5.1 той же ретроспективы требовало **признак включения**: режим
должен вставать по факту, а не по памяти. Правило, которое надо помнить,
не работает — это записано в `/auto` §2в и подтверждено трижды.

🔴 ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЕТ И НЕ УЗНАЕТ:
  · смотрит ли владелец фильм в браузере — вкладка неотличима от фоновой;
  · говорит ли он по телефону не через компьютер;
  · собирается ли начать через минуту.
Она отвечает на «идёт ли сейчас нагрузка на канал и есть ли живое
приложение», а не на «занят ли человек». Ошибка в сторону «занят»
дешевле: лишняя осторожность стоит длины ответа, пропуск — его кадров.

Применение:
    owner_present.py            вердикт и что менять в поведении
    owner_present.py --json     то же машинно
    owner_present.py --selftest канарейка
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time

# Приложения, живой процесс которых сам по себе означает: человек за машиной
# и канал ему нужен. Список намеренно короткий — не «все игры мира», а то,
# что реально стоит на этой машине и что владелец называл сам.
ЖИВЫЕ = {
    "dota2": "игра Dota 2",
    "steam_osx": "клиент Steam",
    "zoom.us": "созвон Zoom",
    "Discord": "Discord",
    "Telegram": "Telegram",
    "Microsoft Teams": "Teams",
    "obs": "запись OBS",
}

ПОРОГ_БАЙТ = 20_000   # Б/с приёма — ниже этого канал считается свободным


def процессы() -> list[str]:
    """Названия живых приложений из списка ЖИВЫЕ."""
    вывод = subprocess.run(["ps", "-Ao", "comm"], capture_output=True,
                           text=True).stdout
    найдено = []
    for ключ, имя in ЖИВЫЕ.items():
        if re.search(re.escape(ключ), вывод, re.I):
            найдено.append(имя)
    return найдено


def _счётчики() -> tuple[int, int]:
    """Байты in/out интерфейса en0 из `netstat -ib`."""
    вывод = subprocess.run(["netstat", "-ib"], capture_output=True,
                           text=True).stdout
    for стр in вывод.splitlines():
        части = стр.split()
        if len(части) > 9 and части[0] == "en0" and ":" in части[3]:
            return int(части[6]), int(части[9])
    return 0, 0


def трафик(секунд: float = 2.0) -> tuple[int, int]:
    """Скорость приёма и отдачи по en0, Б/с.

    🔴 Меряется РАЗНОСТЬЮ ДВУХ ЗАМЕРОВ, а не одним. `netstat` отдаёт
    счётчики с загрузки системы; одно их чтение говорит о сумме за неделю,
    а не о том, что происходит сейчас. Величина, взятая не оттуда, —
    `PIT-197`, и на этом же интерфейсе она уже случалась.
    """
    было = _счётчики()
    time.sleep(секунд)
    стало = _счётчики()
    return (int((стало[0] - было[0]) / секунд),
            int((стало[1] - было[1]) / секунд))


def вердикт(живые: list[str], вниз: int, вверх: int) -> tuple[bool, str]:
    """Занят ли канал владельцем и почему так решено."""
    if живые and вниз >= ПОРОГ_БАЙТ:
        return True, f"{', '.join(живые)} + приём {вниз:,} Б/с"
    if живые:
        return True, f"{', '.join(живые)} запущен, но канал тихий ({вниз:,} Б/с)"
    if вниз >= ПОРОГ_БАЙТ:
        return True, f"приём {вниз:,} Б/с без опознанного приложения"
    return False, f"приложений нет, приём {вниз:,} Б/с"


def selftest() -> bool:
    """Канарейка: вердикт различает четыре сочетания, а не срабатывает всегда."""
    занят_оба, _ = вердикт(["игра"], 90_000, 15_000)
    занят_проц, _ = вердикт(["игра"], 100, 100)
    занят_траф, _ = вердикт([], 90_000, 15_000)
    свободен, _ = вердикт([], 100, 100)
    return занят_оба and занят_проц and занят_траф and not свободен


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true")
    р.add_argument("--selftest", action="store_true")
    a = р.parse_args()

    if a.selftest:
        ок = selftest()
        print("🟢 канарейка: вердикт различает сочетания" if ок
              else "🔴 КАНАРЕЙКА УПАЛА — вердикт не различает")
        return 0 if ок else 1

    живые = процессы()
    вниз, вверх = трафик()
    занят, почему = вердикт(живые, вниз, вверх)

    if a.json:
        print(json.dumps({"занят": занят, "почему": почему, "приложения": живые,
                          "вниз_Б_с": вниз, "вверх_Б_с": вверх},
                         ensure_ascii=False))
        return 0

    if занят:
        print(f"🔴 ВЛАДЕЛЕЦ ЗАНЯТ СЕТЬЮ: {почему}\n")
        print("   Что меняется в работе вахты, пока это так:")
        print("   · отвечать КОРОТКО и РЕДКО — длинный вывод рисуется")
        print("     терминалом и оконным сервером, до 80 % ядра (§4д);")
        print("   · разборы и таблицы писать В ФАЙЛЫ, называя путь строкой;")
        print("   · не слать файлы и ничего не публиковать;")
        print("   · интервал сторожа НЕ менять — правило §0 остаётся;")
        print("   · батчи закрывать МОЖНО: замерено, вклад в канал — ноль.")
    else:
        print(f"🟢 канал свободен: {почему}")
        print("   Штатный режим §0: работать батчами, вывод не экономить.")

    print(f"\n   приём {вниз:,} Б/с · отдача {вверх:,} Б/с"
          f" · порог {ПОРОГ_БАЙТ:,}")
    print("   🔴 Проверка отвечает на «идёт ли нагрузка на канал»,")
    print("      а НЕ на «занят ли человек». Фильм в фоне и телефонный")
    print("      разговор мимо компьютера ей не видны.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
