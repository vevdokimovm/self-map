#!/usr/bin/env python3
"""pitfall_coverage.py — обросли ли ловушки механизмами, или только записаны.

🔴 ВОПРОС ВЛАДЕЛЬЦА 28.08.2026 дословно: «все ли питфолы обросли сторожами,
гейтами, тестами, что были размечены?» Ответ на него был неизвестен: реестр
рос, поле «Гейт:» у карточек заполнялось, но никто ни разу не свёл итог.

ЗАМЕРЕНО 29.08.2026, 149 карточек:

    закрыта                     66  (44 %)
    частично                     2  ( 1 %)
    нельзя принципиально        34  (22 %)
    можно, но не сделано         0  ( 0 %)
    причина есть, разряд неясен 47  (32 %)
    голое «нет» без причины      0

🔴 ТРИ ВЫВОДА, И КАЖДЫЙ СЛЕДУЮЩИЙ ВАЖНЕЕ ПРЕДЫДУЩЕГО.

  · Больше половины ловушек механизма не имеют — и это **не разгильдяйство**:
    все до одной объясняют, почему его нет. Дисциплина «назови причину» держится.
  · Именно поэтому общий процент закрытия **ничего не значит**. Ловушка вида
    «правило противоречит правилу» механизмом не закрывается принципиально,
    и требовать от неё гейта — требовать невозможного. Значимо одно число:
    сколько из **закрываемых** не закрыто. Сейчас это **0**: ни одной
    ловушки, про которую известно, что механизм возможен и не заведён.
  · 🔴 **30 % причин разобрать не удалось, и это находка о реестре, а не
    о инструменте.** Причина написана прозой, и проза не разбирается
    ключевыми словами надёжно — первая редакция словаря дала 0 в очереди
    и 80 в «неясно», вторая (словарь взят из корпуса) — 0 и 47. Дальше
    точность растёт только подгонкой под конкретные формулировки, то есть
    ложно. **Настоящее лечение — не умнее разбор, а явное поле в карточке**
    («механизм: есть · невозможен · возможен, не заведён»), заполняемое
    человеком при заведении. Прозу разбирать не придётся вовсе.

🔴 ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ УМЕЕТ (`71` §7г-бис):

  · **не проверяет, что названный гейт существует и работает.** Карточка
    может ссылаться на проверку, снятую полгода назад, и инструмент
    засчитает её как закрытую. Это разбор ТЕКСТА реестра, не кода;
  · **не судит, тот ли механизм назван** — гейт может ловить соседний класс
    дефектов, а не тот, о котором карточка (ровно этот случай разобран
    29.08.2026: проверка адреса указателя не ловила породивший её дефект);
  · **разряд определяется словами причины**, а слова пишет человек — значит
    разряд ровно настолько честен, насколько честна формулировка.

ЗАПУСК
    pitfall_coverage.py               сводка
    pitfall_coverage.py --queue       только «можно, но не сделано»
    pitfall_coverage.py --selftest    канарейка
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BASE_REPO = Path(__file__).resolve().parent.parent
REGISTRY = BASE_REPO / "reports" / "pitfalls.md"

# 🔴 СЛОВАРЬ ВЗЯТ ИЗ КОРПУСА, А НЕ ПРИДУМАН. Первая редакция угадывала слова
# («неразрешимо», «читающий человек») и разложила 80 карточек из 149 в разряд
# «причина без разряда», а в рабочую очередь — ноль. Прочтение десяти случайных
# причин показало, что реестр пишет о невозможности другими словами: «чистая
# семантика», «суждение о содержании», «не про файлы», «свойство рантайма»,
# «вне репы». Это тот же `PIT-164`: список, составленный без сверки с предметом,
# уверенно докладывает пустоту.
IMPOSSIBLE = ("семантик", "суждение", "не про файлы", "интерпретац", "тон)",
              "рантайм", "вне репы", "не структура файла", "оценка полноты",
              "неразрешим", "читающий человек", "не может быть", "невозможн",
              "не поддаётся", "решает человек", "оценка достижимого",
              "политика доступа", "тайминг", "легитимен", "не имеет доступа")
# Причина намекает, что механизм возможен, — это и есть очередь работ.
FEASIBLE = ("можно", "стоит", "следует", "кандидат", "планируется",
            # «смежный класс уже гейтит» означает ОБРАТНОЕ выполнимости —
              # что закрыт соседний дефект, а этот принципиально не тот.
              # Поймано на PIT-149, попавшем в очередь ошибочно.
            "нужно завести", "напрашивается", "не заводился",
            "пока нет", "ещё нет")


def cards(text: str) -> list[tuple[str, str]]:
    """(имя, тело) по каждой карточке `### PIT-NNN`."""
    parts = re.split(r"\n### (PIT-\d+)", text)
    return [(parts[i], parts[i + 1]) for i in range(1, len(parts), 2)]


def gate_field(body: str) -> str:
    """Значение поля «Гейт:» одной строкой; пусто, если поля нет."""
    m = re.search(r"\*\*Гейт:\*\*\s*(.+?)(?=\n\s*-\s\*\*|\n\n|\Z)", body, re.S)
    return " ".join(m.group(1).split()) if m else ""


def classify(value: str) -> str:
    """Разряд карточки по полю «Гейт»."""
    if not value:
        return "поля нет"
    low = value.lower()
    if low.startswith("частично"):
        return "частично"
    if not low.startswith("нет"):
        return "закрыта"
    # 🔴 Невозможность проверяется ПЕРВОЙ и перевешивает. Причина, называющая
    # и то и другое («нет, и вряд ли будет… можно только по смыслу»), — это
    # «нельзя», а не рабочая задача. Поймано 29.08.2026 на `PIT-167`: слово
    # «можно» стояло внутри оборота «можно только по смыслу», то есть означало
    # ровно обратное, и карточка попала в очередь работ ошибочно.
    if any(w in low for w in IMPOSSIBLE):
        return "нельзя принципиально"
    # Обороты, где «можно» означает невозможность механизма, а не выполнимость.
    if any(w in low for w in ("можно только", "можно лишь", "вряд ли будет")):
        return "нельзя принципиально"
    if any(w in low for w in FEASIBLE):
        return "можно, но не сделано"
    return "нет, причина без разряда"


def selftest() -> bool:
    """Проверяется РАЗЛИЧЕНИЕ: три разряда «нет» не должны сливаться."""
    assert classify("да — `check_cjk`") == "закрыта"
    assert classify("нет — различие смысловое, нужен читающий человек") \
        == "нельзя принципиально"
    assert classify("нет — можно завести проверку по маркеру") \
        == "можно, но не сделано"
    assert classify("нет — не заводился") == "можно, но не сделано"
    # Разряд «без разряда» обязан остаться достижимым: если ЛЮБАЯ причина
    # попадает в один из двух разрядов, инструмент перестаёт признаваться
    # в незнании — а это худший вид отказа (`71` §7ж).
    assert classify("нет — прочерк") == "нет, причина без разряда"
    # Невозможность перевешивает выполнимость: причина, называющая и то и
    # другое, — это «нельзя, но есть смежный класс», а не рабочая задача.
    assert classify("нет — чистая семантика, хотя можно попробовать") \
        == "нельзя принципиально"
    assert classify("частично — ловит только половину") == "частично"
    assert classify("") == "поля нет"
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--queue", action="store_true",
                    help="только «можно, но не сделано» — рабочая очередь")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        try:
            selftest()
        except AssertionError:
            print("🔴 канарейка: разряды сливаются")
            return 1
        print("🟢 канарейка: шесть разрядов различаются")
        return 0

    if not REGISTRY.is_file():
        print(f"🔴 нет реестра: {REGISTRY}")
        return 1

    buckets: dict[str, list[tuple[str, str]]] = {}
    for name, body in cards(REGISTRY.read_text(encoding="utf-8")):
        value = gate_field(body)
        buckets.setdefault(classify(value), []).append((name, value))

    total = sum(len(v) for v in buckets.values())
    queue = buckets.get("можно, но не сделано", [])

    if a.queue:
        print(f"Ловушки, у которых механизм ВОЗМОЖЕН, но не заведён: {len(queue)}\n")
        for name, value in queue:
            print(f"  {name}: {value[:130]}")
        return 0

    print(f"Карточек в реестре: {total}\n")
    order = ["закрыта", "частично", "нельзя принципиально",
             "можно, но не сделано", "нет, причина без разряда", "поля нет"]
    for key in order:
        items = buckets.get(key, [])
        if items:
            print(f"  {key:<26} {len(items):>4}   {len(items) * 100 // total:>3} %")

    print(f"\n🔴 Общий процент закрытия — число, которое НИЧЕГО не значит.")
    print("   Ловушка «правило противоречит правилу» механизмом не закрывается")
    print("   принципиально, и требовать от неё гейта — требовать невозможного.")
    print(f"   Значимое число одно: **{len(queue)}** — механизм возможен, но не")
    print("   заведён. Список: --queue")
    print("\n🔴 Инструмент разбирает ТЕКСТ реестра, а не код: он не проверяет,")
    print("   что названный гейт существует и ловит именно тот класс дефектов.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
