"""Заводит `.git` в рабочей копии репы, НЕ трогая её файлы.

🔴 ГЛАВНОЕ ЧИСЛО ЭТОГО ИНСТРУМЕНТА — 448 КБ вместо 118 МБ.

Замер 09.09.2026 на `it-base` (история на GitHub 118 МБ):

    обычный клон                          ~118 МБ, минуты, рвётся
    --filter=blob:none --depth 1           116 МБ, 54 с
    + --no-checkout                        448 КБ, 2 с

Разница в **260 раз** — и вся она в одном флаге. `clone` по умолчанию
**выкладывает рабочее дерево**, и ради этого тянет содержимое каждого файла.
Выкладывать при этом нечего: файлы уже лежат на диске, репа рабочая.

> **Скачивался не git, а копия того, что уже есть.** Вопрос владельца
> «в чём проблема, если нужен один файл» был точнее моей оценки: нужны
> только метаданные — коммит, деревья, имена и хеши.

🔴 ПОЧЕМУ НЕЛЬЗЯ ПРОСТО `git init` БЕЗ СЕТИ. Без общего предка push будет
отклонён как несвязанная история, а `--force` стёр бы историю на GitHub.
Общего предка можно только получить — но в виде 448 КБ, а не 118 МБ.

🔴 ЧТО НЕ ТРОГАЕТСЯ: рабочие файлы. `read-tree` + `update-ref` ставят
индекс и HEAD, дерево остаётся как было. Обратимо целиком: `rm -rf .git`.

🔴 ПОПРАВКА 09.09.2026: первая редакция считала главным выбор между
`reset --mixed` и `read-tree`. Это было неверно — ни та, ни другая команда
сама по себе не решает вопрос. Решает `core.autocrlf=false`, см. ниже.

Применение:
    git_adopt.py <репа> [<репа>…]     завести
    git_adopt.py --all                по всем репам с remote
    git_adopt.py --dry                показать план
    git_adopt.py --selftest
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _roots import resolve_roots  # noqa: E402

БАЗА = Path(__file__).resolve().parent.parent
OWNER = "vevdokimovm"
ИМЯ = "Vasilii Evdokimov"
ПОЧТА = "vevdokimovm@gmail.com"
ПОПЫТКИ = [0, 5, 15, 30, 60]


def запуск(cmd: list[str], где: Path | None = None) -> tuple[int, str]:
    res = subprocess.run(cmd, cwd=где, capture_output=True, text=True,
                         encoding="utf-8")
    return res.returncode, (res.stdout + res.stderr).strip()


def хуки(корень: Path) -> str | None:
    """Путь к хукам: свои `.githooks` или розданные в `_base/.githooks`.

    🔴 ВОЗВРАЩАЕТ `None`, И ЭТО НАДО ЗАМЕТИТЬ, А НЕ ПРОГЛОТИТЬ.
    09.09.2026 в `ml-base` хуки не подключились: каталог `_base/.githooks`
    существовал, но проверка отработала раньше, чем что-то успело
    появиться, — и функция молча вернула `None`. Итог: репа осталась
    **без защиты от секретов и без проверки подписи**, и снаружи это
    никак не видно.

    Поэтому вызывающий обязан сказать вслух, если хуков не нашлось.
    """
    for кандидат in (".githooks", "_base/.githooks"):
        if (корень / кандидат).is_dir():
            return кандидат
    return None


def завести(корень: Path, репа: str, сухо: bool) -> str:
    if (корень / ".git").exists():
        return "уже есть"
    if сухо:
        return "план: init + config (autocrlf=false) + fetch + read-tree"

    запуск(["git", "init", "-q"], корень)

    # 🔴 ПОДПИСЬ ЛОКАЛЬНАЯ, И ЭТО УСЛОВИЕ №1 ВЛАДЕЛЬЦА. Глобальный конфиг
    # может смениться, переменные окружения — тоже; локальная запись живёт
    # в самой репе и не зависит ни от чего снаружи.
    запуск(["git", "config", "--local", "user.name", ИМЯ], корень)
    запуск(["git", "config", "--local", "user.email", ПОЧТА], корень)

    # 🔴 САМАЯ ВАЖНАЯ СТРОКА ФАЙЛА — `core.autocrlf=false`.
    # В глобальном конфиге владельца стоит `input`, и это оказалось
    # причиной ленивых докачек, а вовсе не выбор между `reset` и `read-tree`.
    #
    # Механизм (найден ресёрчем 09.09.2026, подтверждён замером):
    # хеш локального файла — это не `sha1(файл)`, а `sha1(convert_to_git(файл))`.
    # При `autocrlf=input` конвертация зовёт `has_crlf_in_index()`, которая
    # ЧИТАЕТ СТАРЫЙ БЛОБ из базы объектов — безусловно, даже если в файле
    # нет ни одного CR. Блоба нет → промисор-докачка, **по одному
    # HTTP-запросу на файл**.
    #
    # Замер на двух репах, отличается только эта настройка:
    #
    #   exam-kit (input):  .git 4884 КБ · 29 докачек · status минуты
    #   ml-base  (false):  .git  264 КБ ·  1 докачка · status 1 секунда
    #
    # > **Экономия была не в том, какой командой ставить HEAD, а в том,
    # > заставляем ли мы git читать историю ради подсчёта хеша.**
    #
    # Побочная выгода: `core.safecrlf` в документации прямо предупреждает,
    # что конвертация может ПОРТИТЬ бинарные файлы, ошибочно принятые
    # за текст. В этих репах лежат PDF, PNG и ZIP — риск не абстрактный.
    запуск(["git", "config", "--local", "core.autocrlf", "false"], корень)

    # 🔴 ПОИСК ПЕРЕИМЕНОВАНИЙ ВЫКЛЮЧЕН — найдено опытом на копии 13.09.2026.
    # Коммит в `edu-base` под запретом докачки падал, а без запрета — висел
    # минутами: трассировка показала **1151 запрошенный объект**. Их тянул
    # поиск переименований: чтобы сравнить старый файл с новым, git читает
    # содержимое ОБОИХ, а старых блобов в частичной репе нет.
    #
    # Проверено на двух копиях: `diff --cached` с переименованиями — код 128,
    # с `--no-renames` — код 0; коммит с хуками без сети — код 0.
    # Цена: переименование в выводе видно как «удалён + добавлен». На историю
    # и на то, что уходит на GitHub, не влияет — там только снимки дерева.
    запуск(["git", "config", "--local", "diff.renames", "false"], корень)
    запуск(["git", "config", "--local", "status.renames", "false"], корень)
    путь_хуков = хуки(корень)
    if путь_хуков:
        запуск(["git", "config", "--local", "core.hooksPath", путь_хуков], корень)

    запуск(["git", "remote", "add", "origin",
            f"https://github.com/{OWNER}/{репа}.git"], корень)

    # 🔴 `extensions.partialClone` СТАВИТ ТОЛЬКО `git clone`, А МЫ ЕГО НЕ ЗОВЁМ.
    # Найдено ресёрчем 09.09.2026 и подтверждено на трёх заведённых репах:
    # у всех трёх флага не было. Без него git считает репу не частичной,
    # а **повреждённой**: на любую команду, которой нужен нескачанный объект,
    # он отвечает не «сейчас докачаю», а `unable to read sha1 file` — то есть
    # выглядит как порча репозитория, хотя всё цело.
    #
    # Замер: it-base 1530 недостающих объектов, ml-base 877, exam-kit 62.
    # Все они лежат на GitHub и достаются по требованию — но только если
    # git знает, что репа promisor.
    запуск(["git", "config", "extensions.partialClone", "origin"], корень)

    последний = ""
    for i, пауза in enumerate(ПОПЫТКИ, 1):
        if пауза:
            time.sleep(пауза)
        # 🔴 `main:refs/remotes/origin/main`, А НЕ ПРОСТО `HEAD`.
        # `fetch origin HEAD` тянет коммит, но НЕ создаёт remote-tracking
        # ветку — и upstream потом не к чему привязать. Найдено 09.09.2026
        # на трёх уже заведённых репах: у всех `@{u}` не существовал.
        #
        # Чем это грозило, и почему симптом не наступал сразу:
        #   · `git push` без аргументов — падает или уходит не туда;
        #   · `git status` не показывает «опередил на N коммитов»;
        #   · 🔴 `working_tree_guard.py` считал незапушенные коммиты
        #     через `@{u}` и получал ноль — измеритель эталона ВРАЛ
        #     в одном поле по всем трём репам.
        #
        # Тот же класс, что `extensions.partialClone`: тихо до отказа.
        код, вывод = запуск(
            ["git", "fetch", "-q", "--filter=blob:none", "--depth", "1",
             "--no-tags", "origin", "main:refs/remotes/origin/main"], корень)
        if код == 0:
            break
        последний = вывод.splitlines()[-1] if вывод else "?"
    else:
        return f"🔴 fetch не прошёл за {len(ПОПЫТКИ)} попыток: {последний}"

    # 🔴 НЕ `reset --mixed`, И ЭТО ГЛАВНАЯ СТРОКА ФАЙЛА.
    # Замер 09.09.2026 на `it-base`: `reset --mixed FETCH_HEAD` при
    # частичном клоне запускает ЛЕНИВУЮ ДОКАЧКУ блобов — за десять минут
    # он притащил 2.9 МБ из 118 и продолжал. Вся экономия `--filter`
    # обнулялась одной командой, причём молча: снаружи это просто «долго».
    #
    # `read-tree` строит индекс из ДЕРЕВЬЕВ, которые уже скачаны, и в них
    # есть всё нужное — пути и хеши. Содержимое файлов не требуется:
    # хеш локального файла git считает сам. Замер той же операции: **0 с**,
    # ноль байт из сети.
    #
    # > **Скачивалось то, что уже лежало на диске, — и не потому, что нужно,
    # > а потому, что команда была выбрана неверно.**
    код, вывод = запуск(["git", "read-tree", "FETCH_HEAD"], корень)
    if код != 0:
        return f"🔴 read-tree: {вывод.splitlines()[-1] if вывод else '?'}"
    код, вывод = запуск(["git", "update-ref", "HEAD", "FETCH_HEAD"], корень)
    if код != 0:
        return f"🔴 update-ref: {вывод.splitlines()[-1] if вывод else '?'}"

    # Привязка ветки к удалённой — без неё `push` без аргументов и счётчик
    # «опередил на N» не работают (см. блок про fetch выше).
    запуск(["git", "branch", "--set-upstream-to=origin/main", "main"], корень)

    код, _ = запуск([sys.executable, str(БАЗА / "scripts/attribution_check.py"),
                     "--repo", str(корень)])
    if код != 0:
        return "🔴 атрибуция нарушена сразу после заведения"

    размер = sum(f.stat().st_size for f in (корень / ".git").rglob("*") if f.is_file())
    итог = f"🟢 заведён · .git {размер // 1024} КБ"
    if not путь_хуков:
        # Репа заведена, но защита не встала — это не отказ, а предупреждение,
        # и оно обязано быть видимым: молчание тут неотличимо от успеха.
        итог += "  🔴 БЕЗ ХУКОВ — защита от секретов и подписи не работает"
    return итог


def selftest() -> bool:
    """Канарейка: флаги минимального фетча на месте — без них смысл теряется."""
    исходник = Path(__file__).read_text(encoding="utf-8")
    # 🔴 `core.autocrlf` В СПИСКЕ ОБЯЗАТЕЛЬНОГО. Без него докачка вернётся,
    # и вернётся МОЛЧА: снаружи разница только в том, что «стало медленно».
    нужны = ["--filter=blob:none", "--depth", "read-tree", "update-ref",
             "core.autocrlf", "extensions.partialClone", "diff.renames",
             "--set-upstream-to"]
    if not all(ф in исходник for ф in нужны):
        return False
    # 🔴 И ЗАПРЕЩЁННОЕ ТОЖЕ ПРОВЕРЯЕТСЯ: ни `checkout`, ни `reset` звать
    # нельзя — обе команды при частичном клоне тянут блобы. Канарейка,
    # которая проверяет только наличие нужного, пропустила бы возврат
    # `reset --mixed` при следующей правке.
    # 🔴 ИЩЕМ ВЫЗОВ, А НЕ СЛОВО. Первая редакция искала строку «reset»
    # и нашла её В САМОЙ СЕБЕ — канарейка упала на собственном коде.
    # Ловушка общая: проверка на присутствие текста в файле обязана искать
    # то, что отличает вызов от упоминания, иначе она ловит свою же запись.
    запрещённые_вызовы = ['"git", "check' + 'out"', '"git", "re' + 'set"']
    return all(в not in исходник for в in запрещённые_вызовы)


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("репы", nargs="*")
    р.add_argument("--all", action="store_true")
    р.add_argument("--dry", action="store_true")
    р.add_argument("--selftest", action="store_true")
    a = р.parse_args()

    if a.selftest:
        ок = selftest()
        print("🟢 канарейка: минимальный фетч на месте, checkout не зовётся" if ок
              else "🔴 КАНАРЕЙКА УПАЛА — потерян флаг экономии")
        return 0 if ок else 1

    _, корень_реп, _ = resolve_roots(__file__)
    if a.all:
        имена = sorted(d.name for d in корень_реп.iterdir()
                       if d.is_dir() and not d.name.startswith("."))
    else:
        имена = a.репы
    if not имена:
        р.error("нужны имена реп или --all")

    заведено = 0
    for имя in имена:
        корень = корень_реп / имя
        if not корень.is_dir():
            print(f"  ⚠ {имя}: нет каталога")
            continue
        итог = завести(корень, имя, a.dry)
        print(f"  {имя:<26} {итог}")
        заведено += итог.startswith("🟢")
    print(f"\nзаведено: {заведено} из {len(имена)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
