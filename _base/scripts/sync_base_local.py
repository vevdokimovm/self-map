#!/usr/bin/env python3
"""sync_base_local.py — обновить `_base/` внутри репы до текущего канона base-repo.

🔴 ПОВОД (`PIT-141`). `ADR-004` называет механизм раздачи `_base/` как
`deploy.sh --sync-base` — этого флага нет в коде. `base_coverage.py --adr004`
подтвердил: 51 репа отстала на `_base/BASE_VERSION` v2.92.0 при каноне v3.22+.
Постоянного исполнителя решения так и не появилось (`21-revision-protocol.md` §4г:
«правило без исполнителя есть обещание»).

ЧТО ДЕЛАЕТ. Заменяет `<репа>/_base/` копией канона base-repo целиком (кроме .git
и мусора сборки), пишет `_base/BASE_VERSION` = текущий `VERSION` канона. Отдельный
скрипт, не режим `deploy.sh` — та же логика, что развела `pack_release.py` и
`bump_repo.py`: узкий инструмент безопаснее правки живого 1800-строчного деплойера
без долгого тестирования.

Побочно чинит артефакт iCloud-конфликтов: каталоги с суффиксом ` 2`, `` (2)`` и т.п.
внутри `_base/` — заменяются с нуля, поэтому переживший мусор просто не копируется.

🔴 ИСПРАВЛЕНО 27.08.2026 (найдено прямым вопросом владельца): `--all` раньше
обходил только репы, где `_base/` уже существовал — репа, которая никогда
её не получала (не отставание, а полное отсутствие), молча пропускалась
навсегда. Так `_base/` не заводился в `personal-finance-dss`,
`character-a-analysis`, `portrait-of-taste`, `mission-control` — 47 версий
канона подряд. `--all` теперь обходит **все приватные репы на диске**
(приватность — по `gh repo list`, один вызов на прогон, не по репе) и
заводит `_base/` там, где его ещё не было, а не только обновляет существующий.
Публичные репы по-прежнему не получают `_base/` никогда — правило ADR-004.
Офлайн/`gh` недоступен → громкий отказ с текстом ошибки `gh`, старое
поведение (только репы с уже существующим `_base/`) как ручной обходной путь
(`--repo` поштучно), не тихий фолбэк.

ЗАПУСК
    sync_base_local.py <репа>              одна репа (заводит _base/, если его не было)
    sync_base_local.py --all               все приватные репы на диске
    sync_base_local.py --check             только показать отставание, не трогать
ПРЕДУСЛОВИЯ (проверяются до первой записи; раздача делает `rmtree`, отказ
посреди неё оставляет репу без `_base/` вовсе):
  · канон `base-repo/00-infrastructure/` и `templates/` существуют и непусты;
  · `base-repo/VERSION` читается — иначе `BASE_VERSION` писать нечем;
  · целевая репа существует и это каталог, а не файл;
  · 🔴 в одиночном режиме репа НЕ публичная — предохранитель приватности:
    канон содержит внутренние документы, а публичных реп семь.

ПОСТУСЛОВИЯ (проверяются после):
  · `<репа>/_base/BASE_VERSION` равен `VERSION` канона;
  · `_base/00-infrastructure/` и `_base/templates/` на месте и непусты;
  · `_base/.repo-id` отсутствует — вложенный идентификатор уводит архив
    в чужую репу (`78-base-embedding.md` §3).

ИНВАРИАНТ (верен до и после):
  · в `_base/` нет ничего локального — он сносится целиком и кладётся заново,
    поэтому конфликты слияния невозможны по построению, а не по договорённости.

    🔴 ТОЧНАЯ ГРАНИЦА ЭТОГО ОБЕЩАНИЯ, уточнена 03.09.2026 тестом
    `tests/test_base_sync.sh` S3. Инвариант держится **в момент раздачи**,
    а не непрерывно между раздачами. При совпадении версии И отпечатка репа
    пропускается со словами «уже актуальна» — и локальная правка внутри
    `_base/`, сделанная после раздачи, не обнаруживается: `BASE_FINGERPRINT`
    лежит В КОПИИ и описывает **канон**, а не саму копию.

    Пропуск осознан и остаётся: пересборка — около 28 тысяч удалений на репу,
    и делать её на шестидесяти репах ради недоказанной порчи дорого. Но
    формулировка «конфликты невозможны по построению» была шире правды:
    невозможны они для раздачи, а не для того, кто правит `_base/` руками.
    Кто такое сделал — чинит `--force`.
  · 🔴 отпечаток набора считается ДО записи журнала живости: журнал входит
    в раздаваемое, и замер после записи объявил бы разошедшимися все 54 репы.

ОСМОТР БЕЗ ЗАПИСИ: `--plan` показывает, какие файлы будут снесены, — около
28 тысяч удалений за проход, и до заведения флага их никто не видел заранее.

🔴 РАЗДАЧА — ПОСЛЕДНИЙ ШАГ БАТЧА, А НЕ СЕРЕДИНА. Найдено 03.09.2026.

`system_status.py` показал «отставших от канона: 55» через семь минут после
успешной раздачи, при том что `repo_invariants.py --all` давал 63 чистых
из 63. Два инструмента противоречили друг другу, и оба были правы:
инвариант сверяет ВЕРСИЮ (`BASE_VERSION`), а раздача — ещё и ОТПЕЧАТОК
содержимого. Версия совпадала, содержимое разошлось.

Причина не в инструменте — проверено: отпечаток устойчив между двумя
вызовами подряд, а повторная раздача сразу даёт «уже актуальна». Причина
в порядке действий: **вахта раздала канон, а потом продолжила править
файлы, которые входят в раздаваемое** (`reports/`, `NN-*` киты, `.claude/`).

Отсюда правило, дополняющее шаг 6 `close_batch.py`:

  · раздача идёт ПОСЛЕ всех правок батча, включая записи в реестры
    и журналы кампании — они лежат в `reports/` и раздаются;
  · правка канона после раздачи означает, что раздачу надо повторить,
    иначе следующая вахта увидит расхождение и не поймёт, откуда оно;
  · 🔴 расхождение по ОТПЕЧАТКУ при совпавшей ВЕРСИИ читается как «копию
    правили руками», хотя означать может обратное — что правили канон.
    Различить нельзя ничем: отпечаток симметричен.
"""
