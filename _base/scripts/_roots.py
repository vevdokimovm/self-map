#!/usr/bin/env python3
"""_roots.py — где база и где корень реп, независимо от того, откуда запущен скрипт.

🔴 ЗАДАЧА ВЛАДЕЛЬЦА 28.08.2026 дословно: «ревизия всей системы, направленная
на работу всех реп, когда мы закончим работать из базовой репы и начнём
работать из наследников… как работает деплой в этих случаях, как обновляется
базовая репа, сторожа, гейт, проверки, тесты, создание архивов».

ПРОВЕРЕНО 29.08.2026 на живой репе `chess`, и дефект оказался системным.

Каждый скрипт вычислял корень одинаково:

    BASE_REPO = Path(__file__).resolve().parent.parent
    REPOS = BASE_REPO.parent

Из `base-repo/scripts/` это верно. Из копии кита в наследнике —
`chess/_base/scripts/` — даёт `BASE_REPO = chess/_base` и `REPOS = chess`.
Дальше `REPOS / "chess"` превращается в `chess/chess`, и ритуал отвечает
«каталога не существует». **Так ломались все 20 скриптов сразу**, а не один.

🔴 ПОЧЕМУ ГЕЙТ ПРИ ЭТОМ РАБОТАЛ, И ЭТО ГЛАВНЫЙ УРОК.
`revision_check.py` из наследника отработал и дал зелёный вердикт — потому
что он принимает `--root` и не спрашивает, где корень системы. Проверка,
которой корень не нужен, переносится без изменений; всё, что рассуждает
о соседних репах, — нет. **Работоспособность одного инструмента ничего
не говорит о работоспособности остальных**, и вывод «из наследника всё
работает» по одному гейту был бы ложным.

КАК ОПРЕДЕЛЯЕТСЯ (по факту пути, а не по догадке):

  · путь содержит `/_base/scripts/` → скрипт запущен из **копии кита**
    в репе-наследнике. Корень реп на два уровня выше `_base`, настоящая
    база — `<корень>/base-repo`;
  · иначе — скрипт лежит в самой базе, и работает прежний расчёт.

🔴 ЧЕГО НЕ РЕШАЕТ (`71` §7г-бис):
  · **не делает копию кита равной оригиналу.** Скрипт из `_base/` — снимок
    на момент последней раздачи; он может отставать от базы, и определение
    корня этого не лечит;
  · **не проверяет, что найденная база — та самая.** Если рядом лежит другой
    каталог `base-repo`, будет взят он;
  · **не спасает от запуска из третьего места** (скопировали скрипт в /tmp) —
    тогда корень не определяется, и функция честно сообщает об этом вместо
    того, чтобы угадать.
"""
from __future__ import annotations

from pathlib import Path


def resolve_roots(script_file: str) -> tuple[Path, Path, bool]:
    """(база, корень реп, запущен ли из копии кита).

    `script_file` — всегда `__file__` вызывающего скрипта.
    """
    here = Path(script_file).resolve()
    parts = here.parts
    if "_base" in parts:
        # …/<корень>/<репа>/_base/scripts/<файл>
        i = len(parts) - 1 - parts[::-1].index("_base")
        repo = Path(*parts[:i])           # сама репа-наследник
        repos = repo.parent               # корень всех реп
        return repos / "base-repo", repos, True
    base = here.parent.parent
    return base, base.parent, False


# 🔴 ГДЕ ЛЕЖАТ АРТЕФАКТЫ СИСТЕМЫ — заказ владельца 03.09.2026 23:15:
# *«сделать папку типо developer, куда будут вместо downloads класться все
# артефакты системы, в том числе архивы новых версий. Чтобы всё это было
# отдельно, система от остального. А то в downloads вообще всё скачивается»*.
#
# Разделение по СМЫСЛУ, а не по удобству:
#   · `~/Developer` — то, что система ПРОИЗВОДИТ: архивы релизов, выгрузки
#     деплойера, служебные файлы прогонов;
#   · `~/Downloads` — то, что пришло ИЗВНЕ: браузер, почта, выгрузка Telegram.
#
# Смешение стоило владельцу видимости: 6 архивов системы лежали среди
# случайных `.jpeg` и `.pdf`, и «убрать лишнее из загрузок» означало риск
# снести релиз.
#
# 🔴 ПЕРЕОПРЕДЕЛЯЕТСЯ ОДНОЙ ПЕРЕМЕННОЙ. `BASE_ARTIFACTS=/путь` — нужна тестам
# (иначе они писали бы в настоящую папку владельца, а это уже случалось:
# `test_version_bump.sh` держит отдельную проверку «настоящий ~/Downloads
# не тронут» именно после такого прогона) и переносу на другую машину.
ARTIFACTS_ENV = "BASE_ARTIFACTS"


def artifacts_dir() -> Path:
    """Куда система кладёт то, что производит. Каталог создаётся при обращении.

    🔴 СОЗДАЁТСЯ, А НЕ ТРЕБУЕТСЯ. Отсутствие каталога — не ошибка владельца:
    на свежей машине его просто нет, и падать из-за этого значит требовать
    ручного шага там, где он не нужен.
    """
    import os
    raw = os.environ.get(ARTIFACTS_ENV)
    d = Path(raw).expanduser() if raw else Path.home() / "Developer"
    d.mkdir(parents=True, exist_ok=True)
    return d


def describe(script_file: str) -> str:
    """Строка для вывода: откуда запущено и что из этого следует."""
    base, repos, from_kit = resolve_roots(script_file)
    if from_kit:
        return (f"запущено из копии кита; база — {base}, корень реп — {repos}. "
                f"🔴 копия кита может отставать от базы")
    return f"запущено из базы {base}, корень реп — {repos}"


def selftest() -> bool:
    """Проверяется РАЗЛИЧЕНИЕ двух мест запуска, а не то, что код исполняется."""
    base, repos, kit = resolve_roots("/Users/x/repos/base-repo/scripts/a.py")
    if kit or base != Path("/Users/x/repos/base-repo") or repos != Path("/Users/x/repos"):
        return False
    base, repos, kit = resolve_roots("/Users/x/repos/chess/_base/scripts/a.py")
    # Из наследника: корень тот же, база — настоящая, а НЕ `chess/_base`.
    return (kit and base == Path("/Users/x/repos/base-repo")
            and repos == Path("/Users/x/repos"))


if __name__ == "__main__":
    import sys
    ok = selftest()
    print("🟢 канарейка: запуск из базы и из копии кита различаются"
          if ok else "🔴 канарейка: РАЗЛИЧЕНИЕ СЛОМАНО")
    print(describe(__file__))
    sys.exit(0 if ok else 1)
