#!/usr/bin/env bash
# =============================================================================
# test_stop_latency.sh — за сколько цикл реально выходит по STOP-файлу.
#
# 🔴 ПОВОД — `ROADMAP` §P1.6a, приёмка контура. Один из четырёх её вопросов:
# **«выходит ли цикл по STOP в течение минуты»**. Приёмка целиком требует
# прогона длиннее суток с обрывом сети — его запускает владелец. Но ЭТОТ
# вопрос проверяется в миниатюре, за минуты, и без сети.
#
# Проверять его отдельно стоит потому, что в коде цикла есть комментарий,
# утверждающий ответ: «стоп-файл должен срабатывать в течение минуты,
# а не через часы». Утверждение верно для паузы по лимиту — и требует
# проверки для рабочей фазы.
#
# ЧТО ИЗМЕРЯЕТСЯ: секунды от `touch STOP` до выхода цикла, в двух фазах:
#   · пока цикл МЕЖДУ итерациями — ожидается быстро;
#   · пока внутри цикла РАБОТАЕТ `claude` — ожидается только после её конца.
#
# ГЕРМЕТИЧНОСТЬ. `claude` подменяется стабом-заглушкой, который просто спит:
# ни сети, ни настоящей сессии, ни расхода токенов. Бриф — временный.
#
# ЗАПУСК:  bash 06-autonomous-mode-kit/bin/test_stop_latency.sh
# =============================================================================
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
LOOP="$HERE/autonomous_loop.sh"

PASS=0; FAIL=0
ok(){   printf '  \033[32m✓\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad(){  printf '  \033[31m✗ %s\033[0m\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; FAIL=$((FAIL+1)); }
case_(){ printf '\n\033[1m[%s] %s\033[0m\n' "$1" "$2"; }

SANDBOX="$(mktemp -d)"
trap 'rm -rf "$SANDBOX"; kill %1 2>/dev/null' EXIT

# --- стаб `claude`: спит заданное время и печатает валидный JSON --------------
# Настоящий `claude -p` идёт минуты; для теста хватает секунд, а поведение
# цикла от длительности не зависит — зависит от того, СМОТРИТ ли он STOP.
mkdir -p "$SANDBOX/bin"
cat > "$SANDBOX/bin/claude" <<'STUBEOF'
#!/usr/bin/env bash
sleep "${STUB_WORK_SECONDS:-20}"
printf '{"session_id":"test-session-0001","result":"ok"}\n'
STUBEOF
chmod +x "$SANDBOX/bin/claude"
export PATH="$SANDBOX/bin:$PATH"

# --- бриф: цикл отказывается стартовать без раздела `## СТОП` ------------------
BRIEF="$SANDBOX/brief.md"
cat > "$BRIEF" <<'EOF'
# Тестовый бриф

Ничего не делать — работу изображает стаб.

## СТОП
Останавливаться по STOP-файлу.
EOF

run_dir(){ printf '%s' "$SANDBOX/run$1"; }

# =============================================================================
case_ S1 "STOP между итерациями — цикл выходит быстро"
# =============================================================================
RD="$(run_dir 1)"; mkdir -p "$RD"
export STUB_WORK_SECONDS=3
# Файл ставим ДО старта: цикл проверяет стоп-условия ПЕРЕД работой.
: > "$RD/STOP"
start=$(date +%s)
bash "$LOOP" --brief "$BRIEF" --run-dir "$RD" --hours 1 --max-iter 3 \
  >"$RD/out.txt" 2>&1
elapsed=$(( $(date +%s) - start ))

grep -q 'СТОП-файл найден' "$RD/out.txt" \
  && ok "стоп-файл распознан" || bad "стоп-файл распознан" "$(tail -3 "$RD/out.txt")"
[ "$elapsed" -le 10 ] \
  && ok "выход за ${elapsed}с — до начала работы" \
  || bad "выход до начала работы" "заняло ${elapsed}с"

# =============================================================================
case_ S2 "🔴 STOP во время работы — цикл НЕ реагирует, пока claude не вернулась"
# =============================================================================
# Главный случай набора. Проверяется не «работает ли стоп», а КОГДА он
# срабатывает: разница между «в течение минуты» и «после конца итерации»
# и есть то, что владелец увидит, нажав на тормоз.
RD="$(run_dir 2)"; mkdir -p "$RD"
export STUB_WORK_SECONDS=25
start=$(date +%s)
bash "$LOOP" --brief "$BRIEF" --run-dir "$RD" --hours 1 --max-iter 1 \
  >"$RD/out.txt" 2>&1 &
loop_pid=$!

sleep 5                       # дать войти в работу
touch "$RD/STOP"
stop_at=$(date +%s)
wait "$loop_pid" 2>/dev/null
latency=$(( $(date +%s) - stop_at ))

printf '     задержка выхода после STOP: %sс (работа стаба — %sс)\n' \
  "$latency" "$STUB_WORK_SECONDS"

# 🔴 Утверждение проверяется ОБА раза: и что задержка есть, и какая она.
# Тест не требует «быстро» — он ФИКСИРУЕТ факт. Требовать быстроты значило бы
# объявить дефектом поведение, которое, возможно, менять не нужно.
if [ "$latency" -ge 15 ]; then
  ok "STOP во время работы ждёт конца итерации (${latency}с) — поведение зафиксировано"
else
  ok "STOP прервал работу за ${latency}с — цикл научился прерывать (проверить, чем)"
fi

grep -q 'СТОП-файл найден' "$RD/out.txt" \
  && ok "выход именно по стоп-файлу, а не по MAX_ITER" \
  || bad "выход по стоп-файлу" "$(grep -E 'СТОП|предел|дедлайн' "$RD/out.txt" | head -2)"

# =============================================================================
case_ S3 "журнал прогона пишется и содержит причину выхода"
# =============================================================================
# Без записи в журнал прогон неотличим от несостоявшегося: приёмка контура
# читает журнал, а не экран.
J="$(find "$(run_dir 2)" -name 'journal.tsv' 2>/dev/null | head -1)"
[ -n "$J" ] && [ -s "$J" ] \
  && ok "journal.tsv заведён и не пуст" || bad "journal.tsv заведён" "$(ls "$(run_dir 2)")"
[ -n "$J" ] && grep -q 'stop-file' "$J" \
  && ok "причина выхода записана строкой" \
  || bad "причина выхода записана" "$(tail -2 "$J" 2>/dev/null)"

# =============================================================================
printf '\n\033[1mИТОГ:\033[0m пройдено %d · провалено %d\n' "$PASS" "$FAIL"
if [ "$FAIL" != "0" ]; then
  printf '\033[31mЕсть падения.\033[0m Тормоз автономного прогона — то, чем владелец\n'
  printf 'останавливает работу; его задержка обязана быть известной, а не предполагаемой.\n'
  exit 1
fi
printf '\033[32mВсё зелено.\033[0m\n'
exit 0
