#!/usr/bin/env bash
# =============================================================================
# test_retry_ladder.sh — приёмка §3 скиллы `/auto`: лестница ретрая и пропуск шага.
#
# ЗАЧЕМ. `SKILL.md` §3 описывает поведение при сбое среды: шесть попыток с паузами
# 5/15/30/60/120 с, дальше — ПРОПУСК шага с записью и немедленный переход к следующему.
# До этого теста поведение существовало только текстом (`21` §4г: правило без исполнителя
# есть обещание), и в статусе контура стояло 🔴 «не запускалось».
#
# ЧТО ПРОВЕРЯЕТСЯ — три сценария и переход между ними:
#   A. шаг падает ВСЕГДА          → шесть попыток → пропуск с записью → идём дальше
#   B. шаг падает трижды, потом ок → ретрай доводит до успеха, пропуска нет
#   C. шаг проходит сразу          → ноль лишних попыток
# Плюс главное: после пропуска A прогон НЕ останавливается — B и C выполняются.
#
# ПАУЗЫ. По умолчанию ускорены в 10 раз (SCALE=10), чтобы тест шёл ~23 с вместо ~230 с.
# Проверяется ЛОГИКА и порядок, длительности печатаются отдельно и сверяются с каноном.
# Полный прогон с реальными паузами:  SCALE=1 ./test_retry_ladder.sh
# =============================================================================
set -uo pipefail

SCALE="${SCALE:-10}"
LADDER=(0 5 15 30 60 120)        # пауза ПЕРЕД попыткой N (первая — сразу)
MAX=${#LADDER[@]}
SKIPLOG="$(mktemp)"
FAILED=0

c(){ printf '\033[96m%s\033[0m\n' "$*"; }
g(){ printf '\033[92m%s\033[0m\n' "$*"; }
r(){ printf '\033[91m%s\033[0m\n' "$*"; }
y(){ printf '\033[93m%s\033[0m\n' "$*"; }

# Шаг-заглушка: падает первые $1 раз, дальше проходит. 99 = всегда падает.
attempt_counter_reset(){ echo 0 > "/tmp/_rl_$1"; }
run_step(){                       # run_step <имя> <сколько_раз_падать>
  local name="$1" fail_times="$2" n
  n=$(( $(cat "/tmp/_rl_$name") + 1 ))
  echo "$n" > "/tmp/_rl_$name"
  [ "$n" -le "$fail_times" ] && return 1
  return 0
}

# Лестница: возвращает 0 если шаг прошёл, 1 если исчерпаны попытки.
retry(){                          # retry <имя> <сколько_раз_падать>
  local name="$1" fail_times="$2" i pause
  for (( i=1; i<=MAX; i++ )); do
    pause=$(( LADDER[i-1] / SCALE ))
    [ "$pause" -gt 0 ] && sleep "$pause"
    if run_step "$name" "$fail_times"; then
      g "    ✅ $name: успех с попытки $i"
      return 0
    fi
    y "    ↻ $name: попытка $i неудачна (следующая пауза ${LADDER[i]:-—} с по канону)"
  done
  return 1
}

# Пропуск: запись и переход дальше. Именно ЗДЕСЬ проверяется, что прогон не встал.
skip_step(){                      # skip_step <имя> <причина>
  printf '%s\tпопыток %s\t%s\n' "$1" "$MAX" "$2" >> "$SKIPLOG"
  r "    ⏭  $1: ПРОПУЩЕН после $MAX попыток — записан, идём дальше"
}

check(){                          # check <условие_текст> <ожидание> <факт>
  if [ "$2" = "$3" ]; then g "  ✅ $1"; else r "  ❌ $1: ожидалось «$2», получено «$3»"; FAILED=1; fi
}

c "── Приёмка §3: лестница ретрая и пропуск шага   (SCALE=$SCALE)"
printf '   канон пауз: %s с · попыток: %s\n\n' "${LADDER[*]:1}" "$MAX"

c "A. шаг падает всегда"
attempt_counter_reset A
retry A 99 || skip_step A "среда недоступна (симуляция)"

c "B. шаг падает трижды, затем проходит"
attempt_counter_reset B
retry B 3 || skip_step B "не должен был пропуститься"

c "C. шаг проходит сразу"
attempt_counter_reset C
retry C 0 || skip_step C "не должен был пропуститься"

echo
c "── Проверки"
check "A исчерпал ровно $MAX попыток"        "$MAX" "$(cat /tmp/_rl_A)"
check "B прошёл с 4-й попытки"               "4"    "$(cat /tmp/_rl_B)"
check "C прошёл с 1-й попытки"               "1"    "$(cat /tmp/_rl_C)"
check "пропущен ровно один шаг"              "1"    "$(wc -l < "$SKIPLOG" | tr -d ' ')"
check "пропущен именно A"                    "A"    "$(cut -f1 "$SKIPLOG" | head -1)"
check "прогон НЕ встал: C выполнился после пропуска A" "1" "$(cat /tmp/_rl_C)"

echo
c "── Журнал пропусков (то, что уходит в decisions.md)"
cat "$SKIPLOG"
rm -f "$SKIPLOG" /tmp/_rl_A /tmp/_rl_B /tmp/_rl_C

echo
if [ "$FAILED" -eq 0 ]; then g "ИТОГ: ✅ §3 ПРОЙДЕНА — ретрай доводит до успеха, залипшее пропускается, прогон продолжается"; exit 0
else r "ИТОГ: ❌ §3 НЕ ПРОЙДЕНА"; exit 1; fi
