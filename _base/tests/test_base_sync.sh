#!/usr/bin/env bash
# =============================================================================
# test_base_sync.sh — раздача канона: `sync_base_local.py`.
#
# 🔴 ПОЧЕМУ ИМЕННО ЭТОТ СКРИПТ ПОКРЫВАЕТСЯ ТЕСТОМ РАНЬШЕ ОСТАЛЬНЫХ.
# Он единственный в системе делает `rmtree` по чужой репе — сносит `_base/`
# целиком и кладёт заново, около **28 тысяч удалений за проход**. Ошибка
# в границе того, что считать `_base/`, стоила бы содержимого репы.
#
# И он уже ошибался. 03.09.2026 тест жизненного цикла нашёл: предохранитель
# приватности считал «репы нет в `gh repo list`» равным «репа публичная»,
# и потому отказывал КАЖДОЙ только что заведённой репе. Так `migration`
# прожила шесть часов без канона. Дефект прожил незамеченным, потому что
# отказ выглядел как срабатывание защиты.
#
# ЧТО ПРОВЕРЯЕТСЯ — обещания из шапки самого скрипта:
#   · постусловие: `BASE_VERSION` равен `VERSION` канона;
#   · постусловие: `_base/.repo-id` ОТСУТСТВУЕТ (иначе архив уедет в чужую репу);
#   · инвариант: в `_base/` нет ничего локального — он заменяется целиком;
#   · 🔴 граница `rmtree`: всё, что НЕ в `_base/`, остаётся нетронутым;
#   · предохранитель приватности: публичная репа канон не получает.
#
# ГЕРМЕТИЧНОСТЬ. Песочная база во временном каталоге; `gh` подменяется стабом
# из `tests/bin`, чтобы тест не ходил в сеть и не зависел от состояния GitHub.
#
# ЗАПУСК:  bash tests/test_base_sync.sh      (из корня base-repo)
# =============================================================================
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
BASE="$(cd "$HERE/.." && pwd)"

PASS=0; FAIL=0
ok(){   printf '  \033[32m✓\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad(){  printf '  \033[31m✗ %s\033[0m\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; FAIL=$((FAIL+1)); }
case_(){ printf '\n\033[1m[%s] %s\033[0m\n' "$1" "$2"; }

SANDBOX="$(mktemp -d)"
trap 'rm -rf "$SANDBOX"' EXIT

# --- песочная база ------------------------------------------------------------
SB="$SANDBOX/base-repo"
mkdir -p "$SB/scripts" "$SB/00-infrastructure" "$SB/templates" "$SB/07-media-to-text-lab"
cp "$BASE/scripts/sync_base_local.py" "$SB/scripts/"
cp "$BASE/scripts/_roots.py" "$SB/scripts/"
# 🔴 Зависимость раздатчика с 03.09.2026: исключения из отпечатка задаёт
# признак, а не список (`ADR-007`). Отсутствие модуля — громкий отказ,
# а не тихое «ничего не исключено»: второе поменяло бы смысл отпечатка молча.
cp "$BASE/scripts/runtime_writes.py" "$SB/scripts/"
printf '9.9.9\n' > "$SB/VERSION"
printf '# канон\n' > "$SB/00-infrastructure/01-canon.md"
printf '# шаблон\n' > "$SB/templates/tpl.md"
printf '# кит\n' > "$SB/07-media-to-text-lab/method.md"
printf 'vevdokimovm/base-repo\n' > "$SB/.repo-id"

# --- стаб `gh`: приватными считаются только те, что перечислены -----------------
# Настоящий `gh` ходит в сеть и зависит от состояния GitHub — тест обязан
# быть герметичным, иначе он проверяет чужой сервер, а не наш скрипт.
mkdir -p "$SANDBOX/bin"
cat > "$SANDBOX/bin/gh" <<'GHEOF'
#!/usr/bin/env bash
# Стаб. Приватные: priv-repo. Публичные: pub-repo. Прочих на GitHub нет.
if [ "${1:-}" = "repo" ] && [ "${2:-}" = "list" ]; then
  # 🔴 `isPrivate` — ровно то поле, что запрашивает `private_repo_names`
  # (`--json name,isPrivate`). Здесь стояло `visibility`, и стаб был ЛОЖНЫМ:
  # раздача читает `r.get("isPrivate")` → None → множество приватных пусто.
  # Набор этого не ловил, потому что ветку `--all` не вызывал НИ РАЗУ —
  # а это путь шестого шага ритуала, то есть каждого батча базы.
  # Найдено 03.09.2026 при заведении `test_batch_state.sh`.
  printf '[{"name":"priv-repo","isPrivate":true},{"name":"pub-repo","isPrivate":false}]\n'
  exit 0
fi
exit 1
GHEOF
chmod +x "$SANDBOX/bin/gh"
export PATH="$SANDBOX/bin:$PATH"

SYNC="$SB/scripts/sync_base_local.py"

make_repo(){
  local name="$1" private="$2"
  local r="$SANDBOX/$name"
  mkdir -p "$r/01-own-content"
  printf 'satellite\n' > "$r/.repo-class"
  printf 'vevdokimovm/%s\n' "$name" > "$r/.repo-id"
  printf 'description=тест\nprivate=%s\ntopics=\n' "$private" > "$r/.repo-meta"
  printf '1.0.0\n' > "$r/VERSION"
  printf '# собственный файл репы\n' > "$r/01-own-content/mine.md"
  printf '# README репы\n' > "$r/README.md"
  printf '%s' "$r"
}

# =============================================================================
case_ S1 "приватная репа получает канон; постусловия выполнены"
# =============================================================================
R="$(make_repo priv-repo true)"
out="$(python3 "$SYNC" priv-repo 2>&1)"
rc=$?
[ "$rc" = "0" ] && ok "код возврата 0" || bad "код возврата 0" "$out"

[ -f "$R/_base/BASE_VERSION" ] && ok "_base/BASE_VERSION создан" \
                              || bad "_base/BASE_VERSION создан" "$out"
v="$(cat "$R/_base/BASE_VERSION" 2>/dev/null)"
[ "$v" = "9.9.9" ] && ok "штамп равен VERSION канона" \
                   || bad "штамп равен VERSION канона" "получено '$v'"

[ -s "$R/_base/00-infrastructure/01-canon.md" ] && ok "00-infrastructure на месте" \
                                                || bad "00-infrastructure на месте"
[ -s "$R/_base/templates/tpl.md" ] && ok "templates на месте" || bad "templates на месте"
[ -s "$R/_base/07-media-to-text-lab/method.md" ] \
  && ok "кит NN-* раздан по имени, а не по списку" \
  || bad "кит NN-* раздан по имени" "новый кит не доехал бы до реп"

# 🔴 Вложенный `.repo-id` уводит архив в чужую репу (78-base-embedding.md §3).
[ ! -f "$R/_base/.repo-id" ] && ok "_base/.repo-id отсутствует" \
                             || bad "_base/.repo-id отсутствует" "архив уехал бы в base-repo"

# =============================================================================
case_ S2 "🔴 ГРАНИЦА rmtree: собственное содержимое репы не тронуто"
# =============================================================================
# Ради этого кейса тест и заведён: скрипт сносит `_base/` целиком, и ошибка
# в границе стоила бы содержимого репы. ~28 тысяч удалений за проход.
[ -s "$R/01-own-content/mine.md" ] && ok "собственный каталог репы цел" \
                                  || bad "собственный каталог репы цел" "🔴 rmtree вышел за _base/"
[ -s "$R/README.md" ] && ok "README репы цел" || bad "README репы цел"
[ "$(cat "$R/VERSION")" = "1.0.0" ] && ok "VERSION репы не подменён каноном" \
                                    || bad "VERSION репы не подменён каноном" "$(cat "$R/VERSION")"

# =============================================================================
case_ S3 "инвариант: локальное внутри _base/ не переживает раздачу"
# =============================================================================
# 🔴 ГРАНИЦА ОБЕЩАНИЯ, установлена этим тестом 03.09.2026.
# Шапка гласила: «конфликты слияния невозможны ПО ПОСТРОЕНИЮ». Тест показал,
# что это шире правды: при совпадении версии И отпечатка репа пропускается
# («уже актуальна»), и порча внутри `_base/` не обнаруживается —
# `BASE_FINGERPRINT` лежит В КОПИИ и описывает КАНОН, а не саму копию.
#
# Пропуск осознан (28 тысяч удалений на репу × 60 реп ради недоказанной
# порчи — дорого), поэтому чинилась не логика, а формулировка в шапке.
# Тест закрепляет ОБА поведения: пропуск по умолчанию и починку по --force.
printf 'локальная правка\n' > "$R/_base/самодеятельность.md"
printf 'испорчено\n' > "$R/_base/00-infrastructure/01-canon.md"
python3 "$SYNC" priv-repo >/dev/null 2>&1

[ -f "$R/_base/самодеятельность.md" ] \
  && ok "без --force порча НЕ обнаруживается (задокументированная граница)" \
  || bad "без --force порча не обнаруживается" "поведение изменилось — сверить с шапкой"

python3 "$SYNC" priv-repo --force >/dev/null 2>&1
[ ! -f "$R/_base/самодеятельность.md" ] \
  && ok "--force сносит посторонний файл в _base/" \
  || bad "--force сносит посторонний файл" "инвариант не восстанавливается ничем"
grep -q '^# канон$' "$R/_base/00-infrastructure/01-canon.md" \
  && ok "--force восстанавливает испорченный файл канона" \
  || bad "--force восстанавливает испорченный канон" "$(cat "$R/_base/00-infrastructure/01-canon.md")"

# =============================================================================
case_ S4 "предохранитель приватности: публичная репа канон НЕ получает"
# =============================================================================
P="$(make_repo pub-repo false)"
out="$(python3 "$SYNC" pub-repo 2>&1)"
rc=$?
[ "$rc" != "0" ] && ok "публичная репа отвергнута" || bad "публичная репа отвергнута" "$out"
[ ! -d "$P/_base" ] && ok "_base/ в публичной репе не заведён (ADR-004)" \
                    || bad "_base/ в публичной репе не заведён" "🔴 канон утёк бы на GitHub"

# =============================================================================
case_ S5 "🔴 репы ещё нет на GitHub, но .repo-meta объявляет private=true"
# =============================================================================
# Ровно дефект, из-за которого `migration` прожила шесть часов без канона:
# «нет в списке gh» читалось как «публичная». У свежей репы состояние третье —
# GitHub про неё ещё не знает.
N="$(make_repo brand-new true)"
out="$(python3 "$SYNC" brand-new 2>&1)"
rc=$?
[ "$rc" = "0" ] && ok "свежая репа с private=true получила канон" \
               || bad "свежая репа с private=true получила канон" "$out"
[ -f "$N/_base/BASE_VERSION" ] && ok "канон разложен" || bad "канон разложен"

# И обратное: предохранитель НЕ ослаблен — private=false блокирует так же.
F="$(make_repo brand-new-pub false)"
out="$(python3 "$SYNC" brand-new-pub 2>&1)"
[ $? != 0 ] && ok "свежая репа с private=false отвергнута" \
            || bad "свежая репа с private=false отвергнута" "$out"
[ ! -d "$F/_base" ] && ok "канон не разложен в публичную" || bad "канон не разложен в публичную"

# =============================================================================
case_ S6 "--check и --plan не пишут ничего"
# =============================================================================
C="$(make_repo check-only true)"
python3 "$SYNC" check-only --check >/dev/null 2>&1
[ ! -d "$C/_base" ] && ok "--check не создаёт _base/" || bad "--check не создаёт _base/"
python3 "$SYNC" check-only --plan >/dev/null 2>&1
[ ! -d "$C/_base" ] && ok "--plan не создаёт _base/" || bad "--plan не создаёт _base/"

# =============================================================================
case_ S7 "исключения из отпечатка задаёт ОБЪЯВЛЕНИЕ, а не список (ADR-007)"
# =============================================================================
# 🔴 ПОВОД. `auto.log` лежит в раздаваемом ките `06-*`, и каждая строка о
# закрытом батче меняла отпечаток: 03.09.2026 девять строк сделали 55 реп
# «разошедшимися» (CHANGELOG [4.69.0]). Исключение записали СПИСКОМ из одного
# пути — а перепись по коду нашла семь таких файлов в тот же вечер.
#
# Поэтому тест проверяет не «auto.log исключён», а МЕХАНИЗМ: объявление
# в каталоге управляет отпечатком. Тест на зашитый путь прошёл бы и у списка.
mkdir -p "$SB/06-autonomous-mode-kit/runs" "$SB/12-workstation-kit/snapshots"
printf '2026-09-03\tрепа\tbatch\tv1.0.0: заведено\n' \
  > "$SB/06-autonomous-mode-kit/runs/auto.log"
printf 'runs/auto.log\n' > "$SB/06-autonomous-mode-kit/.runtime-writes"
printf 'snapshots/*.json\n' > "$SB/12-workstation-kit/.runtime-writes"
printf '{}\n' > "$SB/12-workstation-kit/snapshots/2026-09-03.json"

fp(){ python3 -c "
import importlib.util as u
sp = u.spec_from_file_location('s', '$SYNC')
m = u.module_from_spec(sp); sp.loader.exec_module(m)
print(m.kit_fingerprint())
"; }

before="$(fp)"
printf '2026-09-03\tрепа\tbatch\tv1.1.0: следующий\n' \
  >> "$SB/06-autonomous-mode-kit/runs/auto.log"
[ "$before" = "$(fp)" ] && ok "объявленный журнал отпечаток НЕ меняет" \
  || bad "объявленный журнал отпечаток НЕ меняет" "$before → $(fp)"

# 🔴 То, чего список не умел: файл, которого при объявлении ещё не было.
printf '{"новый":1}\n' > "$SB/12-workstation-kit/snapshots/2026-12-31.json"
[ "$before" = "$(fp)" ] && ok "НОВЫЙ файл по шаблону тоже не меняет" \
  || bad "НОВЫЙ файл по шаблону тоже не меняет" "$before → $(fp)"

# Контроль: половина «не изменился» истинна и у мёртвого отпечатка.
printf '# правка кита\n' >> "$SB/07-media-to-text-lab/method.md"
[ "$before" != "$(fp)" ] && ok "правка кита отпечаток МЕНЯЕТ (контроль)" \
  || bad "правка кита отпечаток МЕНЯЕТ" "отпечаток мёртв"

# 🔴 Снять объявление — и тот же файл обязан вернуться в отпечаток.
# Без этой проверки тест не отличает «объявление работает» от «файл
# исключён по какой-то другой причине».
after_edit="$(fp)"
rm "$SB/06-autonomous-mode-kit/.runtime-writes"
[ "$after_edit" != "$(fp)" ] && ok "без объявления журнал ВОЗВРАЩАЕТСЯ в отпечаток" \
  || bad "без объявления журнал возвращается в отпечаток" "объявление ни на что не влияет"

# =============================================================================
case_ S8 "перепись находит необъявленную запись в раздаваемое"
# =============================================================================
# Гейт против восьмого журнала: он должен быть объявлен, а не обнаружен
# через месяц по ложным «разошедшимся» копиям.
RW="$BASE/scripts/runtime_writes.py"
python3 "$RW" --selftest >/dev/null 2>&1 \
  && ok "канарейка признака зелёная (различает объявленное и нет)" \
  || bad "канарейка признака зелёная" "$(python3 "$RW" --selftest 2>&1 | tail -2)"

python3 "$RW" >/dev/null 2>&1 \
  && ok "в живой базе необъявленных записей нет" \
  || bad "в живой базе необъявленных записей нет" "$(python3 "$RW" 2>&1 | tail -4)"

# =============================================================================
printf '\n\033[1mИТОГ:\033[0m пройдено %d · провалено %d\n' "$PASS" "$FAIL"
if [ "$FAIL" != "0" ]; then
  printf '\033[31mЕсть падения.\033[0m Раздатчик канона делает rmtree по чужим репам — чинить первым.\n'
  exit 1
fi
printf '\033[32mВсё зелено.\033[0m\n'
exit 0
