#!/usr/bin/env bash
# =============================================================================
# test_repo_lifecycle.sh — жизненный цикл репы: конструктор, инвариант, откат.
#
# 🔴 ЗАКАЗ ВЛАДЕЛЬЦА 02.09.2026: «введи уже TDD в базу репу чтобы на все наши
# служебки были реальыне гейты тесты сторожи скрипты что то что проверяет что
# инструкци выполняются а не просто лежат».
#
# ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ ИМЕННО ЗДЕСЬ. Конструктор реп (`new_repo.py`),
# деструктор (`retire_repo.py`) и раздатчик канона (`sync_base_local.py`)
# были БЕЗ ТЕСТОВ ВОВСЕ — при том что именно они создают объекты, с которыми
# работает вся остальная система. Репа `migration` прожила шесть часов
# без `_base/` ровно потому, что проверять было нечем.
#
# ЧТО ПРОВЕРЯЕТСЯ. Не «скрипт запустился», а СВОЙСТВА:
#   · конструктор создаёт объект, удовлетворяющий инварианту;
#   · при нарушении инварианта объекта НЕ ОСТАЁТСЯ (сильная гарантия);
#   · раздача канона — часть построения, а не отдельный шаг;
#   · публичная репа канон не получает (ADR-004).
#
# ГЕРМЕТИЧНОСТЬ. Песочница — копия базы во временном каталоге; корень реп
# вычисляется от пути скрипта (`_roots.py`), поэтому репы создаются ТАМ,
# а не в `~/repos`. Ни сети, ни `gh`, ни настоящих реп.
#
# ЗАПУСК:  bash tests/test_repo_lifecycle.sh      (из корня base-repo)
# Код возврата 0 — всё зелено; 1 — есть падения.
# =============================================================================
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
BASE="$(cd "$HERE/.." && pwd)"

PASS=0; FAIL=0
ok(){   printf '  \033[32m✓\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad(){  printf '  \033[31m✗ %s\033[0m\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; FAIL=$((FAIL+1)); }
case_(){ printf '\n\033[1m[%s] %s\033[0m\n' "$1" "$2"; }

SANDBOX="$(mktemp -d)"
trap 'rm -rf "$SANDBOX"' EXIT

# --- песочная база -----------------------------------------------------------
# Корень реп определяется как родитель каталога базы, поэтому достаточно
# положить базу в `$SANDBOX/base-repo` — репы поедут в `$SANDBOX/`.
SB="$SANDBOX/base-repo"
mkdir -p "$SB/templates" "$SB/reports/releases"
cp -R "$BASE/scripts" "$SB/scripts"
cp "$BASE/VERSION" "$SB/VERSION"
cp "$BASE/templates/gitignore.template" "$SB/templates/gitignore.template" 2>/dev/null \
  || printf '*.pyc\n.DS_Store\n' > "$SB/templates/gitignore.template"
printf '# песочная база\n' > "$SB/README.md"
printf 'vevdokimovm/base-repo\n' > "$SB/.repo-id"
printf 'infra\n' > "$SB/.repo-class"
printf 'description=песочница\nprivate=true\ntopics=\n' > "$SB/.repo-meta"

NEW="$SB/scripts/new_repo.py"
INV="$SB/scripts/repo_invariants.py"

# =============================================================================
case_ L1 "конструктор строит репу, удовлетворяющую инварианту"
# =============================================================================
out="$(python3 "$NEW" test-alpha --class satellite --desc "тестовая" --apply 2>&1)"
rc=$?
if [ -d "$SANDBOX/test-alpha" ]; then ok "каталог создан"; else bad "каталог создан" "$out"; fi
[ "$rc" = "0" ] && ok "код возврата 0" || bad "код возврата 0" "получен $rc"

# Фаза born: только что созданная репа ещё не выпускалась — требовать
# от неё записи в журнале выпусков значит не дать ей родиться.
inv="$(python3 "$INV" "$SANDBOX/test-alpha" --phase born 2>&1)"
printf '%s' "$inv" | grep -q "инвариант выполнен" \
  && ok "инвариант выполнен сразу после создания" \
  || bad "инвариант выполнен сразу после создания" "$inv"

# =============================================================================
case_ L2 "канон раздаётся конструктором, а не отдельным шагом"
# =============================================================================
# 🔴 Ровно дефект `migration`: раздача была советом в конце вывода.
if [ -f "$SANDBOX/test-alpha/_base/BASE_VERSION" ]; then
  ok "_base/BASE_VERSION заведён"
  want="$(cat "$SB/VERSION")"; have="$(cat "$SANDBOX/test-alpha/_base/BASE_VERSION")"
  [ "$want" = "$have" ] && ok "штамп совпадает с каноном ($have)" \
                        || bad "штамп совпадает с каноном" "канон $want, штамп $have"
else
  bad "_base/BASE_VERSION заведён" "файла нет — раздача не выполнена"
fi

# =============================================================================
case_ L3 "публичная репа канон НЕ получает (ADR-004)"
# =============================================================================
out="$(python3 "$NEW" test-public --class product --desc "публичная" --private false --apply 2>&1)"
if [ -d "$SANDBOX/test-public" ]; then
  [ -d "$SANDBOX/test-public/_base" ] \
    && bad "публичная репа без _base/" "канон утёк бы на GitHub" \
    || ok "публичная репа без _base/"
else
  bad "публичная репа создана" "$out"
fi

# =============================================================================
case_ L4 "СИЛЬНАЯ ГАРАНТИЯ: нарушен инвариант — объекта не остаётся"
# =============================================================================
# Ломаем раздатчик канона: конструктор обязан не суметь достроить объект
# и откатить всё созданное, а не оставить полурепу.
mv "$SB/scripts/sync_base_local.py" "$SB/scripts/sync_base_local.py.off"
out="$(python3 "$NEW" test-broken --class satellite --desc "сломанная" --apply 2>&1)"
rc=$?
mv "$SB/scripts/sync_base_local.py.off" "$SB/scripts/sync_base_local.py"

[ "$rc" != "0" ] && ok "код возврата ненулевой" || bad "код возврата ненулевой" "получен 0"
printf '%s' "$out" | grep -q "ИНВАРИАНТ НАРУШЕН" \
  && ok "нарушение названо явно" || bad "нарушение названо явно" "$out"
if [ -d "$SANDBOX/test-broken" ]; then
  bad "каталог откачен" "на диске осталась НЕПОЛНАЯ репа — половина объекта хуже его отсутствия"
else
  ok "каталог откачен — недособранной репы не осталось"
fi

# =============================================================================
case_ L5 "предусловия конструктора: имя и повторное создание"
# =============================================================================
out="$(python3 "$NEW" "ПЛОХОЕ_ИМЯ" --class satellite --desc "x" --apply 2>&1)"
[ $? != 0 ] && ok "кириллица и подчёркивания отвергнуты" \
            || bad "кириллица и подчёркивания отвергнуты" "$out"

out="$(python3 "$NEW" test-alpha --class satellite --desc "повтор" --apply 2>&1)"
rc=$?
[ "$rc" != "0" ] && ok "повторное создание отвергнуто" \
                 || bad "повторное создание отвергнуто" "репа перезаписана"
[ -f "$SANDBOX/test-alpha/_base/BASE_VERSION" ] \
  && ok "существующая репа не пострадала" \
  || bad "существующая репа не пострадала" "отказ повредил уже созданное"

# =============================================================================
case_ L6 "инвариант ловит подделки на живой репе"
# =============================================================================
rm -f "$SANDBOX/test-alpha/_base/BASE_VERSION"
python3 "$INV" "$SANDBOX/test-alpha" 2>&1 | grep -q "R-06" \
  && ok "R-06 ловит снесённый канон" || bad "R-06 ловит снесённый канон"

printf '9.9.9\n' > "$SANDBOX/test-alpha/VERSION"
python3 "$INV" "$SANDBOX/test-alpha" 2>&1 | grep -q "R-08" \
  && ok "R-08 ловит README, отставший от VERSION" \
  || bad "R-08 ловит README, отставший от VERSION"

python3 "$INV" "$SANDBOX/test-alpha" 2>&1 | grep -q "R-09" \
  && ok "R-09 ловит невыпущенную версию" || bad "R-09 ловит невыпущенную версию"

# =============================================================================
case_ L8 "ДЕСТРУКТОР: вечные классы не расформировываются"
# =============================================================================
# 🔴 Деструктор до 03.09.2026 не был покрыт ничем — при том что он единственный
# скрипт, способный СНЕСТИ каталог с диска. Тестируется он здесь, а не отдельно:
# конструктор и деструктор — пара, и проверять их врозь значит пропустить
# случаи, где один оставляет то, что другой не убирает.
RET="$SB/scripts/retire_repo.py"

# `infra` и `core` объявлены вечными (76-repo-classes.md §1). Отказ обязан
# наступать ДО любой записи, а не после половины работы.
printf 'core\n' > "$SANDBOX/test-alpha/.repo-class"
out="$(python3 "$RET" test-alpha --apply 2>&1)"
rc=$?
[ "$rc" != "0" ] && ok "класс core отвергнут" || bad "класс core отвергнут" "$out"
[ -d "$SANDBOX/test-alpha" ] && ok "каталог не тронут при отказе" \
                            || bad "каталог не тронут при отказе" "репа снесена вопреки отказу"
printf 'satellite\n' > "$SANDBOX/test-alpha/.repo-class"

# =============================================================================
case_ L9 "ДЕСТРУКТОР: план по умолчанию, снос только по --apply"
# =============================================================================
out="$(python3 "$RET" test-alpha 2>&1)"
[ -d "$SANDBOX/test-alpha" ] \
  && ok "без --apply репа на месте (сухой прогон)" \
  || bad "без --apply репа на месте" "снесена без явного разрешения"

# 🔴 Инвариант деструктора, названный в его же шапке: архивы не удаляются
# НИКОГДА. У реп нет локального `.git`, архив — единственный экземпляр версии.
mkdir -p "$SANDBOX/dl" && : > "$SANDBOX/dl/test-alpha-v1.0.0.zip"
python3 "$RET" test-alpha >/dev/null 2>&1
[ -f "$SANDBOX/dl/test-alpha-v1.0.0.zip" ] \
  && ok "архив релиза не тронут" || bad "архив релиза не тронут" "архив исчез"

# =============================================================================
case_ L7 "канарейка самого инварианта проходит"
# =============================================================================
if python3 "$INV" --selftest >/dev/null 2>&1; then
  ok "selftest инварианта зелёный"
else
  bad "selftest инварианта зелёный" "правила перестали ловить то, ради чего заведены"
fi

# =============================================================================
case_ L8 "счётчик ссылок: живой артефакт и недостижимый различаются"
# =============================================================================
# 🔴 ЖИЗНЕННЫЙ ЦИКЛ ОБЪЕКТА — не только рождение и смерть. Между ними объект
# кем-то удерживается, и удалять удерживаемый — оставить висячие ссылки
# (`OOP_MECHANISMS.md` §2). Механизм заведён 03.09.2026 после того, как вахта
# ВРУЧНУЮ грепала ссылки перед переименованием путей на маке и нашла два
# `@`-импорта в `~/.claude/CLAUDE.md`: проверка сработала, потому что о ней
# вспомнили.
RC="$BASE/scripts/refcount.py"

python3 "$RC" --selftest >/dev/null 2>&1 \
  && ok "канарейка индекса ссылок зелёная" \
  || bad "канарейка индекса ссылок зелёная" "$(python3 "$RC" --selftest 2>&1 | tail -2)"

# Проверяется РАЗЛИЧЕНИЕ на песочном корпусе, а не на живой базе: тест,
# опирающийся на текущее содержимое репы, проверяет содержимое, а не механизм.
T="$SANDBOX/refs"; mkdir -p "$T"
printf 'смотри [подробнее](живой.md)\n' > "$T/навигатор.md"
printf '# живой\n' > "$T/живой.md"
printf '# сирота\n\nсирота.md зовёт только себя\n' > "$T/сирота.md"

out="$(python3 - "$BASE/scripts" "$T" <<'PYEOF'
import sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])          # путь ARGV, не интерполяция в heredoc
import refs_index
base = Path(sys.argv[2])
corpus = refs_index.build(base)
live = refs_index.unreferenced([Path("живой.md")], corpus)
orph = refs_index.unreferenced([Path("сирота.md")], corpus)
print("live_orphan" if live else "live_ok")
print("orphan_found" if orph else "orphan_missed")
PYEOF
)"
printf '%s' "$out" | grep -q 'live_ok' \
  && ok "упомянутый файл НЕ числится недостижимым" \
  || bad "упомянутый файл НЕ числится недостижимым" "$out"

# 🔴 Половина «сирота найдена» истинна и у проверки, объявляющей сиротой всё.
# Поэтому проверяются оба направления, и самоупоминание не спасает от сиротства:
# иначе сирот не будет никогда — почти каждый файл называет себя в шапке.
printf '%s' "$out" | grep -q 'orphan_found' \
  && ok "недостижимый найден, самоупоминание не спасло" \
  || bad "недостижимый найден" "$out"

# =============================================================================
printf '\n\033[1mИТОГ:\033[0m пройдено %d · провалено %d\n' "$PASS" "$FAIL"
if [ "$FAIL" != "0" ]; then
  printf '\033[31mЕсть падения.\033[0m Конструктор объектов сломан — чинить до всего остального.\n'
  exit 1
fi
printf '\033[32mВсё зелено.\033[0m\n'
exit 0
