#!/usr/bin/env bash
# =============================================================================
# test_batch_state.sh — состояние батча: `close_batch.py --state`.
#
# 🔴 ПОВОД — ЖИВОЙ ОБРЫВ 03.09.2026. Ритуал базы упёрся в таймаут на шестом
# шаге: раздача канона оборвалась, четыре последние по алфавиту репы остались
# без канона (у одной — `_base/` скопирован, а штампы не записаны), —
# и `--state` ответил «батч закрыт **ПОЛНОСТЬЮ**».
#
# Утверждение было ложным И В СТОРОНУ УСПОКОЕНИЯ: состояние знало о трёх
# числах (VERSION · архив · журнал) при ритуале из ШЕСТИ шагов. Шаг, который
# не проверяется вовсе, хуже шага, который проверяется плохо: второй хотя бы
# может оказаться красным.
#
# 🔴 И ВТОРАЯ ПОЛОВИНА ПОВОДА: `close_batch.py` — центральный инструмент
# системы, вызываемый каждым батчем, — не был покрыт НИ ОДНИМ набором.
# Обрыв нашёл владелец, а не тест.
#
# ЧТО ПРОВЕРЯЕТСЯ — РАЗЛИЧЕНИЕ трёх исходов, а не один «хороший»:
#   1. канон роздан      → «закрыт полностью»
#   2. репа отстала      → «раздача НЕ завершена», и слова «полностью» НЕТ
#   3. раздача отказала  → «проверить НЕ УДАЛОСЬ» (`71` §7ж), а не тишина
#
# Третий — главный. Утверждение «всё хорошо» и «проверить не смогли» обязаны
# различаться: молчащий отказ выглядит успехом.
#
# ГЕРМЕТИЧНОСТЬ. Песочная база во временном каталоге, стаб `gh`, свои репы.
# Ни сети, ни настоящих реп, ни записи в `~/Downloads`.
#
# ЗАПУСК:  bash tests/test_batch_state.sh      (из корня base-repo)
# =============================================================================
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
BASE="$(cd "$HERE/.." && pwd)"

PASS=0; FAIL=0
ok(){   printf '  \033[32m✓\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad(){  printf '  \033[31m✗ %s\033[0m\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; FAIL=$((FAIL+1)); }
case_(){ printf '\n\033[1m[%s] %s\033[0m\n' "$1" "$2"; }

SANDBOX="$(mktemp -d)"
trap 'rm -rf "$SANDBOX"' EXIT

# --- песочная база ------------------------------------------------------------
SB="$SANDBOX/base-repo"
mkdir -p "$SB/scripts" "$SB/reports/releases" "$SB/00-infrastructure" \
         "$SB/06-autonomous-mode-kit/runs" "$SB/06-autonomous-mode-kit/bin"
for f in close_batch.py sync_base_local.py _roots.py runtime_writes.py; do
  cp "$BASE/scripts/$f" "$SB/scripts/"
done
cp "$BASE/06-autonomous-mode-kit/bin/auto_log.py" "$SB/06-autonomous-mode-kit/bin/"
printf '1.0.0\n' > "$SB/VERSION"
printf '# песочная база\n' > "$SB/README.md"
printf '# канон\n' > "$SB/00-infrastructure/01-canon.md"
printf 'vevdokimovm/base-repo\n' > "$SB/.repo-id"
printf 'infra\n' > "$SB/.repo-class"
printf 'description=песочница\nprivate=true\ntopics=\n' > "$SB/.repo-meta"

# батч «закрыт»: три числа сходятся — остаётся ровно вопрос раздачи
printf 'дата\t1.0.0\t10\t1000\n' > "$SB/reports/releases/LEDGER.tsv"
printf '2026-09-03T00:00:00\tbase-repo\tbatch\tv1.0.0: песочный\n' \
  > "$SB/06-autonomous-mode-kit/runs/auto.log"

# --- репа-наследник -----------------------------------------------------------
R="$SANDBOX/priv-repo"
mkdir -p "$R/01-own"
printf 'satellite\n' > "$R/.repo-class"
printf 'vevdokimovm/priv-repo\n' > "$R/.repo-id"
printf 'description=тест\nprivate=true\ntopics=\n' > "$R/.repo-meta"
printf 'своё\n' > "$R/01-own/file.md"

# --- стаб `gh`: без сети -------------------------------------------------------
mkdir -p "$SANDBOX/bin"
cat > "$SANDBOX/bin/gh" <<'GHEOF'
#!/usr/bin/env bash
if [ "${1:-}" = "repo" ] && [ "${2:-}" = "list" ]; then
  # 🔴 ПОЛЕ `isPrivate`, а не `visibility` — так спрашивает `private_repo_names`
  # (`gh repo list --json name,isPrivate`). Стаб с `visibility` возвращает
  # ПУСТОЕ множество приватных, раздача молча не видит ни одной репы,
  # и тест на `--all` зеленеет, ничего не проверив.
  printf '[{"name":"priv-repo","isPrivate":true}]\n'
  exit 0
fi
exit 1
GHEOF
chmod +x "$SANDBOX/bin/gh"
export PATH="$SANDBOX/bin:$PATH"

CB="$SB/scripts/close_batch.py"
state(){ python3 "$CB" base-repo --state 2>&1; }

# =============================================================================
case_ B1 "канон НЕ роздан — состояние обязано это назвать"
# =============================================================================
out="$(state)"
printf '%s' "$out" | grep -q 'раздача НЕ завершена' \
  && ok "необходанный канон назван" || bad "необходанный канон назван" "$out"

# 🔴 Ровно то, что случилось вживую: три числа сошлись, и состояние
# объявило «полностью», умолчав про шестой шаг.
printf '%s' "$out" | grep -q 'закрыт полностью' \
  && bad "🔴 сказано «закрыт полностью» при нероз­данном каноне" "$out" \
  || ok "слова «закрыт полностью» НЕТ (тот самый дефект)"

printf '%s' "$out" | grep -q 'sync_base_local.py --all' \
  && ok "названо, чем чинить" || bad "названо, чем чинить" "$out"

# =============================================================================
case_ B2 "канон роздан — состояние обязано сказать «полностью»"
# =============================================================================
# Половина «не сказал полностью» истинна и у сломанной проверки, которая
# не говорит так НИКОГДА. Поэтому проверяется и обратный исход.
python3 "$SB/scripts/sync_base_local.py" --all >/dev/null 2>&1
out="$(state)"
printf '%s' "$out" | grep -q 'закрыт полностью' \
  && ok "после раздачи — «закрыт полностью»" \
  || bad "после раздачи — «закрыт полностью»" "$out"

printf '%s' "$out" | grep -q 'раздача НЕ завершена' \
  && bad "остался ложный сигнал о раздаче" "$out" \
  || ok "ложного сигнала нет"

# =============================================================================
case_ B3 "🔴 раздача ОТКАЗАЛА — это НЕ «всё хорошо» (71 §7ж)"
# =============================================================================
# Главный случай набора. Недоступный `gh` роняет раздачу; молчаливое
# «полностью» здесь означало бы, что отказ проверки читается как её успех.
cat > "$SANDBOX/bin/gh" <<'GHEOF'
#!/usr/bin/env bash
echo "gh: недоступен" >&2
exit 1
GHEOF
chmod +x "$SANDBOX/bin/gh"

out="$(state)"
printf '%s' "$out" | grep -q 'НЕ УДАЛОСЬ' \
  && ok "отказ раздачи назван отказом, а не успехом" \
  || bad "отказ раздачи назван отказом" "$out"

printf '%s' "$out" | grep -q 'закрыт полностью' \
  && bad "🔴 отказ проверки прочитан как «всё хорошо»" "$out" \
  || ok "«полностью» при отказе НЕ печатается"

# =============================================================================
case_ B4 "у ЧУЖОЙ репы раздачи нет — состояние про неё молчит"
# =============================================================================
# Шаг 6 существует только у базы. Спрашивать раздачу с наследника значило бы
# требовать исполнения правила, которого он не адресат, — и красить его
# красным вечно.
printf '2.0.0\n' > "$R/VERSION"
printf 'дата\t2.0.0\t10\t1000\n' > "$R/../priv-repo/LEDGER-stub" 2>/dev/null
out="$(python3 "$CB" priv-repo --state 2>&1)"
printf '%s' "$out" | grep -q 'раздача' \
  && bad "с наследника спрашивают раздачу" "$out" \
  || ok "про раздачу у наследника не сказано ни слова"

# =============================================================================
printf '\n\033[1mИТОГ:\033[0m пройдено %d · провалено %d\n' "$PASS" "$FAIL"
if [ "$FAIL" != "0" ]; then
  printf '\033[31mЕсть падения.\033[0m Состояние батча врёт — по нему судят, доделан ли батч.\n'
  exit 1
fi
printf '\033[32mВсё зелено.\033[0m\n'
exit 0
