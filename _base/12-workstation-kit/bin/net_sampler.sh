#!/usr/bin/env bash
# =============================================================================
# net_sampler.sh — пассивный ряд трафика во время матча.
#
# 🔴 ПОВОД: заказ владельца 05.09.2026 — «следи активно за трафиком доты,
# я сейчас играю, наблюдай для анализа».
#
# 🔴 ДВА ЗАПРЕТА, ОБА ИЗ СОБСТВЕННЫХ РАЗБОРОВ, И ОБА ЖЁСТКИЕ:
#
#   1. НИ ОДНОЙ СЕТЕВОЙ ПРОБЫ. Ни ping, ни speedtest, ни отправки файлов.
#      Разбор `dota-and-claude-coexistence-2026-09-05.md` §2г: отправка
#      пачки скриншотов забила upstream и кончилась разрывом сессии
#      (↑88 → 632). Измеритель, который сам занимает канал, измеряет себя.
#
#   2. НИ ОДНОГО ОБХОДА ПРОЦЕССОВ. `/machine --watch` уронил игру
#      с 60 до 5 FPS именно этим: полный `ps` шестьдесят раз в минуту.
#
# ЧТО ЧИТАЕТСЯ: только счётчики ядра `netstat -ib` (готовые числа, без
# опроса сети) и `sysctl vm.loadavg`. Стоимость — микросекунды.
#
# ВЫХОД: TSV, по строке на отсчёт: время · ↓Б/с · ↑Б/с · load1.
#
# ЗАПУСК:  bash 12-workstation-kit/bin/net_sampler.sh <секунд> [интервал]
# =============================================================================
set -u
DUR="${1:-600}"
STEP="${2:-5}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/observations/net-samples.tsv"
IFACE="${IFACE:-en0}"

read_counters() {
  netstat -ib | awk -v i="$IFACE" '$1==i && $4 ~ /:/ {print $7, $10; exit}'
}
# 🔴 Строка с MAC-адресом ($4 содержит ":") — единственная, где счётчики
# не задвоены: netstat печатает интерфейс несколько раз, по адресу на строку.

[ -f "$OUT" ] || printf 'время\tвниз_Бс\tвверх_Бс\tload1\n' > "$OUT"

prev="$(read_counters)"
[ -z "$prev" ] && { echo "нет интерфейса $IFACE" >&2; exit 2; }
pi=$(echo "$prev" | cut -d' ' -f1); po=$(echo "$prev" | cut -d' ' -f2)

end=$(( $(date +%s) + DUR ))
while [ "$(date +%s)" -lt "$end" ]; do
  sleep "$STEP"
  cur="$(read_counters)"
  ci=$(echo "$cur" | cut -d' ' -f1); co=$(echo "$cur" | cut -d' ' -f2)
  din=$(( (ci - pi) / STEP )); dout=$(( (co - po) / STEP ))
  l1=$(sysctl -n vm.loadavg | awk '{print $2}')
  printf '%s\t%s\t%s\t%s\n' "$(date +%H:%M:%S)" "$din" "$dout" "$l1" >> "$OUT"
  pi=$ci; po=$co
done
