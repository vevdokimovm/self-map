#!/usr/bin/env python3
"""Разбор ряда `conn_sampler.sh`: когда туннель умирал и что было вокруг.

🔴 ЗАЧЕМ. Смерть процесса — единственное событие, которое видно в этом
ряду и невидимо во всех остальных: имя процесса не меняется, меняется
тождество (`PIT-199`). Разбор писался вручную трижды за утро, и один раз
дал ложный вывод про «ритм 24 минуты» из одной длительности.

Печатает по каждой смене процесса:
  · сколько прожил предыдущий — 🔴 **все длительности сразу**, чтобы
    одна не выглядела законом;
  · путь до и после — сменился адрес или шлюз (сота) или нет;
  · соединения перед смертью — падали (сервер закрыл) или держались;
  · обе задержки — росла ли дальняя при ровной ближней.

🔴 ЧЕГО НЕ ДЕЛАЕТ: не называет причину. Даёт три различающих признака
и число событий; вывод — за читающим.

Применение: analyze_conn.py <conn-samples.tsv> [--вокруг N]
"""

import argparse
import statistics as st
from pathlib import Path

ВОКРУГ = 5


def читать(path: Path) -> list[dict[str, str]]:
    строки = [l.rstrip("\n").split("\t")
              for l in path.read_text(encoding="utf-8").splitlines()]
    if len(строки) < 2:
        raise SystemExit("в ряду меньше двух строк")
    шапка = строки[0]
    return [dict(zip(шапка, r)) for r in строки[1:] if len(r) == len(шапка)]


def число(s: str) -> float | None:
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def в_секунды(живёт: str) -> int | None:
    """`MM:SS` или `HH:MM:SS` в секунды. Иначе None — молча не гадаем."""
    части = живёт.split(":")
    if not all(p.isdigit() for p in части) or not 2 <= len(части) <= 3:
        return None
    сек = 0
    for p in части:
        сек = сек * 60 + int(p)
    return сек


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("файл", type=Path)
    p.add_argument("--вокруг", type=int, default=ВОКРУГ,
                   help=f"строк до и после смены (по умолчанию {ВОКРУГ})")
    a = p.parse_args()

    d = читать(a.файл)
    for нужен in ("время", "pid", "живёт"):
        if нужен not in d[0]:
            raise SystemExit(f"нет столбца «{нужен}» — это не ряд conn_sampler")

    смены = [k for k in range(1, len(d)) if d[k]["pid"] != d[k - 1]["pid"]]
    print(f"замеров {len(d)} · {d[0]['время']} – {d[-1]['время']} · "
          f"смен процесса: {len(смены)}")

    # 🔴 ВСЕ длительности сразу — иначе одна выглядит законом (PIT-198).
    жизни = []
    for k in смены:
        пред = d[k - 1]
        сек = в_секунды(пред["живёт"])
        if сек is not None and пред["pid"] != "-":
            жизни.append((пред["pid"], пред["живёт"], сек))
    if жизни:
        print("\nизмеренные жизни процессов:")
        for pid, стр, сек in жизни:
            print(f"  {pid:<8} {стр:>9}  ({сек} с)")
        if len(жизни) >= 2:
            сек = [s for _, _, s in жизни]
            print(f"  разброс: {min(сек)} – {max(сек)} с, то есть в "
                  f"{max(сек) / max(min(сек), 1):.0f} раз")
        print(f"  🔴 полностью измеренных жизней: {len(жизни)} — "
              f"{'этого мало для периода' if len(жизни) < 10 else 'можно считать период'}")

    есть_шлюз = "шлюз_мс" in d[0]
    for k in смены:
        печ = d[max(0, k - a.вокруг):k + a.вокруг]
        print(f"\n=== смена в {d[k]['время']}: {d[k-1]['pid']} → {d[k]['pid']} ===")
        столбцы = ["время", "pid", "живёт", "всего_TCP", "мой_ip", "шлюз", "rtt_мс"]
        if есть_шлюз:
            столбцы.append("шлюз_мс")
        print("  " + "".join(f"{c:>12}" for c in столбцы))
        for r in печ:
            метка = " ←" if r is d[k] else ""
            print("  " + "".join(f"{r.get(c,'')[:11]:>12}" for c in столбцы) + метка)

        # 🔴 СТРОКА СМЕРТИ (`pid = -`) НЕ ЯВЛЯЕТСЯ ПРЕДШЕСТВЕННИКОМ.
        # Первая редакция печатала для перехода `- → новый` строку
        # «соединения падали: 41 → 0», сравнивая живой процесс с нулём
        # мёртвой строки. Число верное, смысл ложный: падение произошло
        # раньше, в предыдущем переходе. Поймано первым же прогоном.
        до = [r for r in d[max(0, k - a.вокруг):k] if r["pid"] != "-"]
        после = [r for r in d[k:k + a.вокруг] if r["pid"] != "-"]
        if d[k - 1]["pid"] == "-":
            print("\n  (подъём после смерти — признаки считаны на предыдущем переходе)")
        elif до and после:
            путь_тот_же = (до[-1].get("мой_ip") == после[0].get("мой_ip")
                           and до[-1].get("шлюз") == после[0].get("шлюз"))
            tcp = [int(r["всего_TCP"]) for r in до if r["всего_TCP"].isdigit()]
            print(f"\n  путь до и после: {'ТОТ ЖЕ' if путь_тот_же else '🔴 СМЕНИЛСЯ'}")
            if len(tcp) >= 2:
                print(f"  соединения перед смертью: {tcp[0]} → {tcp[-1]} "
                      f"({'падали' if tcp[-1] < tcp[0] else 'держались или росли'})")
            дальние = [число(r.get("rtt_мс", "")) for r in до]
            дальние = [v for v in дальние if v]
            if len(дальние) >= 3:
                print(f"  дальняя задержка перед смертью: "
                      f"{дальние[0]:.1f} → {дальние[-1]:.1f} мс")
            if есть_шлюз:
                ближние = [число(r.get("шлюз_мс", "")) for r in до]
                ближние = [v for v in ближние if v]
                if len(ближние) >= 3:
                    print(f"  ближняя задержка перед смертью: "
                          f"{ближние[0]:.2f} → {ближние[-1]:.2f} мс")

    if есть_шлюз:
        пары = [(число(r["rtt_мс"]), число(r["шлюз_мс"])) for r in d]
        пары = [(x, y) for x, y in пары if x and y]
        if len(пары) >= 5:
            т = [x for x, _ in пары]; ш = [y for _, y in пары]
            print(f"\nдоля ближнего конца: "
                  f"{100 * st.median(ш) / st.median(т):.1f} % "
                  f"(медианы {st.median(ш):.2f} и {st.median(т):.1f} мс, "
                  f"{len(пары)} замеров)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
