#!/bin/bash
# Секундный ряд: ловит КОРОТКОЕ зависание, невидимое на шаге 15 с.
#
# 🔴 ЗАЧЕМ. 05.09.2026 владелец сообщил о трёх полных зависаниях игры,
# а сборщик с шагом 15 с не показал ни смерти туннеля (процесс прожил
# 30 минут подряд), ни провала соединений. Событие короче шага наблюдения
# невидимо ПО ПОСТРОЕНИЮ — ряд надо сгущать, а не толковать имеющийся.
#
# 🔴 ИМЕНА ПЕРЕМЕННЫХ — ТОЛЬКО ЛАТИНИЦА. Первая редакция звала их
# по-русски (`пред`, `КОНЕЦ`), как в питоновских инструментах рядом.
# Bash разбирает `пред=1 2` НЕ как присваивание, а как команду, и падает
# с `command not found`, а следом `unbound variable` из-за `set -u`.
# Python допускает Unicode в идентификаторах, shell — нет; перенос
# привычки между языками стоил запуска. Комментарии по-русски можно.
#
# 🔴 РЯД НЕ СТРОГО СЕКУНДНЫЙ, И ЭТО НАДО ЗНАТЬ ТОМУ, КТО ЕГО СЧИТАЕТ.
# Замер 05.09.2026 по 3766 шагам: медиана 1 с, но 801 шаг из 3766
# (21 %) выходит по 2 с — `ping` ждёт таймаута, — и среднее 1.22 с.
# Значит длительность события НЕЛЬЗЯ считать числом строк: так она
# занижается на четверть. Считать только разностью отметок времени.
# Разобрано в `PIT-203`.
#
# Пробы только до ШЛЮЗА — локальный канал, наружу ничего не уходит.
set -u
DUR="${1:-1800}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/observations/freeze-watch.tsv"
GW="$(ipconfig getoption en0 router 2>/dev/null || echo 172.20.10.1)"
[ -s "$OUT" ] || printf 'время\tвниз_Б\tвверх_Б\tшлюз_мс\tтун_pid\n' > "$OUT"

read_en0() { netstat -ib | awk '$1=="en0" && $4 ~ /:/ {print $7" "$10; exit}'; }

prev="$(read_en0)"
end=$(( $(date +%s) + DUR ))
while [ "$(date +%s)" -lt "$end" ]; do
  sleep 1
  cur="$(read_en0)"
  gw="$(ping -c 1 -W 900 "$GW" 2>/dev/null | awk -F'=' '/time=/{split($NF,a," "); print a[1]; exit}')"
  pid="$(pgrep -x Tunnel | head -1)"
  awk -v a="$prev" -v b="$cur" -v t="$(date +%H:%M:%S)" -v g="${gw:--}" -v p="${pid:--}" 'BEGIN{
    split(a,x," "); split(b,y," ");
    printf "%s\t%d\t%d\t%s\t%s\n", t, y[1]-x[1], y[2]-x[2], g, p
  }' >> "$OUT"
  prev="$cur"
done
