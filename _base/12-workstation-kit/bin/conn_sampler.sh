#!/bin/bash
# Число живых соединений туннеля и его PID — посекундный ряд.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СБОРЩИК, А НЕ СТОЛБЕЦ В interplay_probe.sh.
# Тот уже работает, а bash читает скрипт по мере исполнения: правка
# на живом сдвигает строки под работающим процессом (`00-CLAUDE-STOP.md` §4).
# Отдельный файл добавляет наблюдение, ничего не ломая.
#
# 🔴 ЗАЧЕМ ВООБЩЕ. 05.09.2026 одно окно дало 1.8 млн пакетов не в срок,
# и две версии — «память душит туннель» и «игра переподключается» — дают
# одинаковую картину. Различает их ровно одно: рвались ли соединения.
# Этого счётчика не было, поэтому вопрос остался открытым.
#
# Применение: conn_sampler.sh [секунд_всего] [шаг_секунд]
set -u
DUR="${1:-1800}"
STEP="${2:-5}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/observations/conn-samples.tsv"
[ -s "$OUT" ] || printf 'время\tpid\tмб\tживёт\tвсего_TCP\tустановлено\tк_серверу\tмой_ip\tшлюз\trtt_мс\tшлюз_мс\n' > "$OUT"

END=$(( $(date +%s) + DUR ))
while [ "$(date +%s)" -lt "$END" ]; do
  pid="$(pgrep -x Tunnel | head -1)"
  if [ -n "$pid" ]; then
    # 🔴 Один вызов lsof на виток: он не бесплатный, и два вызова ради
    # двух чисел удваивают цену наблюдения без нужды.
    snap="$(lsof -nP -p "$pid" 2>/dev/null | awk '$8=="TCP"{print $9, $10}')"
    total="$(printf '%s\n' "$snap" | grep -c '\->' || true)"
    estab="$(printf '%s\n' "$snap" | grep -c 'ESTABLISHED' || true)"
    tosrv="$(printf '%s\n' "$snap" | grep -c ':8443' || true)"
    # 🔴 RSS и возраст — ради проверяемого предсказания: у расширений
    # NetworkExtension в macOS жёсткий потолок памяти. Если туннель гибнет
    # об него, перед смертью RSS упирается в потолок, а возраст обнуляется.
    rss="$(ps -o rss= -p "$pid" | tr -d ' ')"
    # 🔴 НЕ `-o etimes=`: в macOS такого ключа нет, и `ps` вываливает
    # СПИСОК ДОПУСТИМЫХ КЛЮЧЕЙ в stdout вместо числа — то есть портит
    # столбец, не падая. Поймано первым же прогоном (§2г, правило 3).
    age="$(ps -o etime= -p "$pid" | tr -d ' ')"
    # 🔴 ПУТЬ ДО СЕТИ — чтобы РАЗЛИЧИТЬ три версии смерти туннеля.
    # Смена соты у хотспота меняет адрес или шлюз; сброс сессии сервером
    # оставляет путь прежним. Без этих полей обе версии дают одну картину
    # (05.09.2026, версия периода отозвана прямым опытом).
    ip="$(ipconfig getifaddr en0 2>/dev/null || echo '-')"
    # 🔴 НЕ `route -n get default`: маршрут по умолчанию идёт через utun,
    # и шлюза у него нет — поле выходит пустым. Нужен шлюз ФИЗИЧЕСКОГО
    # интерфейса, он и меняется при смене соты у хотспота.
    gw="$(ipconfig getoption en0 router 2>/dev/null || echo '-')"
    # 🔴 ЗАДЕРЖКА ДО ШЛЮЗА — разделяет БЛИЖНИЙ конец канала от дальнего.
    # Замер 05.09.2026: до телефона 3.3 мс при 100 мс до сервера, то есть
    # вклад Mac и Wi-Fi — 3 % от общей задержки. Без этого столбца любой
    # скачок RTT неразличим: локальный он или за телефоном.
    # `-W 1000` обязателен: без него потерянная проба вешает виток цикла.
    gwrtt="$(ping -c 1 -W 1000 "${gw:-172.20.10.1}" 2>/dev/null \
             | awk -F'=' '/time=/{split($NF,a," "); print a[1]; exit}')"
    rtt="$(nettop -x -l 1 2>/dev/null \
           | awk '/:8443/ {for(j=1;j<=NF;j++) if($j=="ms"){s+=$(j-1); n++}} END{if(n) printf "%.1f", s/n; else print "-"}')"
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(date +%H:%M:%S)" "$pid" \
      "$(( ${rss:-0} / 1024 ))" "${age:-?}" "$total" "$estab" "$tosrv" \
      "${ip:--}" "${gw:--}" "${rtt:--}" "${gwrtt:--}" >> "$OUT"
  else
    printf '%s\t-\t0\t0\t0\t0\t0\t%s\t%s\t-\t-\n' "$(date +%H:%M:%S)" \
      "$(ipconfig getifaddr en0 2>/dev/null || echo '-')" \
      "$(ipconfig getoption en0 router 2>/dev/null || echo '-')" >> "$OUT"
  fi
  sleep "$STEP"
done
