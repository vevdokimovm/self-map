#!/usr/bin/env python3
"""Сравнение ДВУХ окон секундного ряда `freeze_watch.sh`.

🔴 ГЛАВНОЕ ЗДЕСЬ — НЕ СРАВНЕНИЕ, А ТРИ ОТКАЗА ЕГО ДЕЛАТЬ.

Опыт «мешает ли вахта игре» ставился так: окно, где вахта молчит, против
окна, где вахта работает. 05.09.2026 обе половины дали ноль провалов —
и это чуть не стало выводом «пачки ни при чём». Разбор показал три дыры,
и каждая закрыта здесь проверкой ДО всякого счёта:

1. **живость** — если игра в окне не шла, проваливаться было нечему,
   и ноль провалов не значит ничего. Считается по ТРЕТЯМ окна: матч может
   кончиться в середине, и медиана всего окна это спрячет;
2. **настоящий ли контраст** — окна различались всплесками в 13 раз,
   а объёмом всего в 1.35. Почти весь объём обоих окон — сама игра
   (~17 кБ/с). Опыт различал окна не по тому, чем собирался;
3. **хватает ли событий** — провалы редкие и слипшиеся: шесть из них легли
   в одну минуту. Ноль против нуля на двух окнах по 3.5 минуты — это одно
   сравнение, а не закон (`PIT-198`).

Применение:
    compare_windows.py <freeze-watch.tsv> A:ЧЧ:ММ:СС-ЧЧ:ММ:СС B:ЧЧ:ММ:СС-ЧЧ:ММ:СС
"""

import argparse
import statistics as st
import sys

ЖИВОСТЬ = 20_000       # Б/с медианы — ниже этого игра не идёт
ПАЧКА = 100_000        # Б/с отдачи — выше этого секунда считается всплеском
КОНТРАСТ = 2.0         # во столько раз объёмы окон должны различаться


class Окно:
    """Кусок секундного ряда с показаниями и проверками годности."""

    def __init__(self, имя: str, строки: list):
        self.имя = имя
        self.вх = [int(ч[1]) for ч in строки]
        self.исх = [int(ч[2]) for ч in строки]
        self.секунд = len(строки)

    def трети(self) -> list:
        """Медианы входящего по трём равным частям окна."""
        т = self.секунд // 3
        куски = (self.вх[:т], self.вх[т:2 * т], self.вх[2 * т:])
        return [st.median(к) if к else 0 for к in куски]

    def жива(self) -> bool:
        return all(м >= ЖИВОСТЬ for м in self.трети())

    def всплесков(self) -> int:
        return sum(1 for x in self.исх if x > ПАЧКА)

    def отдано(self) -> int:
        return sum(self.исх)


def читать(путь: str, с: str, по: str) -> list:
    """Строки ряда, попавшие во временные границы окна."""
    вышло = []
    for стр in open(путь, encoding='utf-8'):
        ч = стр.rstrip('\n').split('\t')
        if len(ч) >= 3 and с <= ч[0] <= по:
            вышло.append(ч)
    return вышло


def разобрать_окно(путь: str, задание: str) -> Окно:
    """Разбирает «имя:начало-конец» и достаёт этот кусок ряда."""
    имя, _, границы = задание.partition(':')
    с, _, по = границы.partition('-')
    строки = читать(путь, с.strip(), по.strip())
    if not строки:
        sys.exit(f"🔴 окно {имя} ({с}–{по}) пустое — в ряду таких секунд нет")
    return Окно(f"{имя} ({с}–{по})", строки)


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument('файл')
    р.add_argument('окно_а', help='имя:ЧЧ:ММ:СС-ЧЧ:ММ:СС')
    р.add_argument('окно_б', help='имя:ЧЧ:ММ:СС-ЧЧ:ММ:СС')
    а = р.parse_args()

    А = разобрать_окно(а.файл, а.окно_а)
    Б = разобрать_окно(а.файл, а.окно_б)

    print("=== ПОКАЗАНИЯ ===")
    for о in (А, Б):
        print(f"\n{о.имя} — {о.секунд} с")
        print(f"  медиана входящего  {st.median(о.вх):>10,.0f} Б/с")
        print(f"  трети              " + " · ".join(f"{м:,.0f}" for м in о.трети()))
        print(f"  отдано             {о.отдано() / 1048576:>10.2f} МБ")
        print(f"  секунд-всплесков   {о.всплесков():>10d}")

    print("\n=== ОТКАЗЫ ===")
    отказ = False

    for о in (А, Б):
        if not о.жива():
            print(f"🔴 {о.имя}: игра шла НЕ ВСЁ окно — считать провалы нельзя,")
            print("   их отсутствие ничего не значило бы: нечему проваливаться.")
            отказ = True

    доля = max(А.отдано(), Б.отдано()) / max(1, min(А.отдано(), Б.отдано()))
    if доля < КОНТРАСТ:
        print(f"🔴 контраст по ОБЪЁМУ всего в {доля:.2f} раза — этого мало.")
        print("   Всплесков может различаться в разы, но канал грузит объём,")
        print("   а он в обоих окнах почти целиком принадлежит самой игре.")
        print("   Окна различались не тем, чем задумывалось.")
        отказ = True

    if отказ:
        print("\nСравнение НЕ проводится. Исправьте окна и повторите.")
        return 2

    print("🟢 оба окна годны и различаются по объёму — сравнение законно.")
    print("\n🔴 И даже тогда это ОДНО сравнение, а не закон: провалы редкие")
    print("   и слипшиеся. Вывод пишется как наблюдение, пока окон не станет")
    print("   несколько каждого вида (`PIT-198`).")
    return 0


if __name__ == '__main__':
    sys.exit(main())
