#!/bin/bash
# Ряд игровых показателей с ЭКРАНА: FPS и сетевой график клиента Dota.
#
# 🔴 ЗАЧЕМ. Снаружи процесса FPS и внутриигровой пинг не видны ничем —
# их знает только клиент. Полчаса 05.09.2026 ушло на разбор туннеля,
# пока на экране стояло «FPS 36»: искали там, где умели мерить.
# Владелец: «ты разве не можешь получить к нему доступ?» — мог.
#
# Снимается ТОЛЬКО угол с числами (180×20 логических точек), не весь экран:
# кадр целиком — 8 МБ, угол — 9 КБ. Дешевле и для машины, и для чтения.
#
# 🔴 Координаты `-R` в ЛОГИЧЕСКИХ точках, а файл выходит ретиновый вдвое.
# Полный экран 2560×1600 пикселей — это 1280×800 точек, и `-R` считает
# по вторым. Промах даёт «rect does not intersect any displays».
#
# Применение: fps_probe.sh [кадров] [шаг_секунд] [каталог]
set -u
N="${1:-12}"
STEP="${2:-5}"
DIR="${3:-${TMPDIR:-/tmp}/fps-probe}"
RECT="${FPS_RECT:-1050,0,180,20}"
SELF_DIR="$(cd "$(dirname "$0")" && pwd)"

mkdir -p "$DIR"
rm -f "$DIR"/f_*.png "$DIR"/strip.png
: > "$DIR/log.tsv"

i=0
while [ "$i" -lt "$N" ]; do
  i=$((i + 1))
  printf -v tag "%03d" "$i"
  screencapture -x -R "$RECT" "$DIR/f_$tag.png" 2>/dev/null
  printf '%s\t%s\t%s\n' "$tag" "$(date +%H:%M:%S)" \
    "$(sysctl -n vm.loadavg | awk '{print $2}')" >> "$DIR/log.tsv"
  [ "$i" -lt "$N" ] && sleep "$STEP"
done

python3 "$SELF_DIR/stitch_png.py" "$DIR/strip.png" "$DIR"/f_*.png
echo "порядок строк — сверху вниз, времена в $DIR/log.tsv"
