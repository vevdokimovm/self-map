#!/usr/bin/env python3
"""Отличается ли FPS после смены настройки — или это разброс.

🔴 ЗАЧЕМ. 05.09.2026 владельцу предложено менять настройки Dota по одной
и сравнивать кадры. Без этого инструмента сравнение выглядело бы так:
«до было 36, стало 39, лучше». Замер того же дня: десять кадров подряд
БЕЗ единого изменения дали 29 · 31 · 33 · 34 · 36 · 37 · 37 · 38 · 42 · 43 —
размах 14 кадров. Разница в 3 кадра внутри такого разброса не значит ничего.

> **Прибавка меньше разброса — это не прибавка.** А разброс здесь
> сравним с самой величиной, потому что FPS зависит от того, что
> происходит на экране: в бою кадров меньше, чем на пустой карте.

🔴 ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ УМЕЕТ И НЕ БУДЕТ. Он не знает, что творилось
на экране. Два ряда, снятых в бою и вне боя, он сравнит честно по числам
и выдаст разницу, которой нет. Поэтому оба ряда снимаются в СОПОСТАВИМЫХ
условиях, и это работа человека, а не программы.

Применение:
    fps_compare.py --до 42 43 31 36 33 --после 48 51 44 47 45
"""

import argparse
import statistics as st
import sys

МАЛО = 8          # кадров в ряду — меньше этого вывод не делается


def свод(имя: str, ряд: list) -> None:
    print(f"{имя:<8} n={len(ряд):<3} медиана {st.median(ряд):>5.1f} · "
          f"размах {min(ряд)}–{max(ряд)} · разброс ±{st.pstdev(ряд):.1f}")


def main() -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--до", nargs="+", type=float, required=True)
    р.add_argument("--после", nargs="+", type=float, required=True)
    a = р.parse_args()

    до, после = a.до, a.после
    свод("до", до)
    свод("после", после)

    разница = st.median(после) - st.median(до)
    шум = max(st.pstdev(до), st.pstdev(после))
    print(f"\nразница медиан: {разница:+.1f} кадра · шум ±{шум:.1f}")

    print()
    if len(до) < МАЛО or len(после) < МАЛО:
        print(f"🔴 РЯДЫ КОРОТКИЕ (нужно хотя бы по {МАЛО} кадров в каждом).")
        print("   Вывод не делается: на пяти кадрах разброс не отличить")
        print("   от разницы. Доснимите и повторите.")
        return 2

    if abs(разница) < шум:
        print("🔴 РАЗНИЦЫ НЕ ВИДНО: она меньше собственного разброса рядов.")
        print("   Это НЕ значит «настройка не помогла» — значит, что этот")
        print("   замер не способен отличить помощь от шума. Чтобы увидеть")
        print("   прибавку меньше разброса, нужны ряды длиннее, а не смелее")
        print("   истолкованные.")
        return 1

    сторона = "выросли" if разница > 0 else "УПАЛИ"
    print(f"🟢 кадры {сторона} на {abs(разница):.1f} — больше разброса ±{шум:.1f}.")
    print("   🔴 И это по-прежнему ОДНО сравнение двух рядов. Оно станет")
    print("   правилом, только если повторится при возврате настройки назад")
    print("   и повторной смене (`PIT-198`).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
