#!/usr/bin/env python3
"""Какой механизм стоял за каждым зависанием игры.

🔴 ЗАЧЕМ. `analyze_freeze.py` отвечает «связь пропадала тогда-то».
Это не диагноз: 05.09.2026 два эпизода одного утра оказались двумя
РАЗНЫМИ поломками, и по секундному ряду они неразличимы —

  09:55–09:58  процесс туннеля жив, но до сервера 100–125 мс вместо 78
               и соединений к нему 8–13 вместо 30–34: деградация пути;
  10:35–10:36  процесс туннеля УМЕР и родился дважды подряд: все TCP
               оборвались разом, игре нечего было переспрашивать.

Лечатся они по-разному, а выглядят одинаково — «игра зависла».
Здесь оба ряда сводятся по времени, и каждому эпизоду называется
механизм — либо честно печатается, что данных для выбора не хватило.

Применение:
    diagnose_episode.py [--freeze <tsv>] [--conn <tsv>] [--с ЧЧ:ММ:СС] [--по ...]
"""

import argparse
import statistics as st
from pathlib import Path

КИТ = Path(__file__).resolve().parent.parent
ЖИВОСТЬ = 20_000
ДОЛЯ_ПРОВАЛА = 0.15
ПАЧКА = 500_000
ЗАПАС = 20          # с — насколько шире эпизода смотреть ряд соединений


def в_сек(t: str) -> int:
    ч, м, с = (int(x) for x in t.split(":"))
    return ч * 3600 + м * 60 + с


def читать(путь: Path, с, по) -> list[dict]:
    строки = [l.rstrip("\n").split("\t")
              for l in путь.read_text(encoding="utf-8").splitlines()]
    шапка = строки[0]
    d = [dict(zip(шапка, r)) for r in строки[1:] if len(r) == len(шапка)]
    if с:
        d = [r for r in d if r["время"] >= с]
    if по:
        d = [r for r in d if r["время"] <= по]
    return d


def эпизоды(d: list[dict], порог: float) -> list[tuple[int, int]]:
    """Подряд идущие плохие секунды, слитые в эпизоды через разрывы до 15 с.

    🔴 СЛИВАЮТСЯ НАМЕРЕННО. Обрыв на три минуты даёт мигания выше порога,
    и посекундная дробилка разрезает его на 17 «событий». Семнадцать
    независимых событий и один обрыв — разные диагнозы под одним числом.
    """
    плохо = [i for i, r in enumerate(d) if int(r["вниз_Б"]) < порог]
    if not плохо:
        return []
    итог, нач, пред = [], плохо[0], плохо[0]
    for i in плохо[1:]:
        if i - пред > 15:
            итог.append((нач, пред))
            нач = i
        пред = i
    итог.append((нач, пред))
    return итог


def механизм(эп_с: str, эп_по: str, conn: list[dict]) -> list[str]:
    """Что говорит ряд соединений про этот отрезок времени."""
    низ, верх = в_сек(эп_с) - ЗАПАС, в_сек(эп_по) + ЗАПАС
    кусок = [r for r in conn if низ <= в_сек(r["время"]) <= верх]
    if not кусок:
        return ["🔴 ряда соединений на это время НЕТ — механизм не определён"]

    вывод = []
    смерти = [r["время"] for r in кусок if r["pid"] == "-"]
    пиды = [r["pid"] for r in кусок if r["pid"] != "-"]
    if смерти:
        вывод.append(f"🔴 ПРОЦЕСС ТУННЕЛЯ УМЕР в {', '.join(смерти)} — "
                     f"все TCP оборвались разом")
    if len(set(пиды)) > 1:
        вывод.append(f"🔴 туннель перерождался: {' → '.join(dict.fromkeys(пиды))}")

    ртт = [float(r["rtt_мс"]) for r in кусок
           if r["rtt_мс"] not in ("-", "", "0.0")]
    к_серв = [int(r["к_серверу"]) for r in кусок if r["pid"] != "-"]
    if ртт:
        вывод.append(f"до сервера: медиана {st.median(ртт):.0f} мс · "
                     f"макс {max(ртт):.0f}")
    if к_серв:
        вывод.append(f"соединений к серверу: {min(к_серв)}–{max(к_серв)}")
    if not смерти and len(set(пиды)) <= 1:
        вывод.append("🟡 процесс жил всё время — значит рвался ПУТЬ, "
                     "а не туннель")
    return вывод


def main() -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--freeze", default=КИТ / "observations/freeze-watch.tsv")
    р.add_argument("--conn", default=КИТ / "observations/conn-samples.tsv")
    р.add_argument("--dns", default=КИТ / "observations/dns-samples.tsv")
    р.add_argument("--с")
    р.add_argument("--по")
    a = р.parse_args()

    d = читать(Path(a.freeze), a.с, a.по)
    if not d:
        raise SystemExit("в окне нет замеров")
    вниз = [int(r["вниз_Б"]) for r in d]
    мед = st.median(вниз)
    print(f"окно {d[0]['время']} – {d[-1]['время']}, {len(d)} секунд · "
          f"медиана входящего {мед:,.0f} Б/с")

    # 🔴 ДЫРЫ В РЯДУ — проверка была заведена в `analyze_freeze.py`
    # (`PIT-201`) и НЕ перенесена сюда. Два инструмента читают один ряд,
    # и один из них молчал о пропусках: окно 11:21–11:25 показало
    # 176 строк на 281 секунду, и разрыв был виден только вычитанием.
    # Проверка, живущая в одном из двух читателей, защищает половину
    # случаев — то есть не защищает.
    дыры = []
    for i in range(1, len(d)):
        разрыв = в_сек(d[i]["время"]) - в_сек(d[i - 1]["время"])
        if разрыв > 5:
            дыры.append((d[i - 1]["время"], d[i]["время"], разрыв))
    if дыры:
        всего = sum(x[2] for x in дыры)
        слово = "ДЫРА" if len(дыры) % 10 == 1 and len(дыры) % 100 != 11 else "ДЫР"
        print(f"\n🔴 В РЯДУ {len(дыры)} {слово}, всего {всего} с без наблюдения:")
        for нач, кон, дл in дыры[:5]:
            print(f"   {нач} → {кон}  ({дл} с)")
        print("   Эпизод внутри дыры не виден по построению — "
              "не считать это время тихим.")

    if мед < ЖИВОСТЬ:
        print(f"\n🔴 ИГРА В ЭТОМ ОКНЕ НЕ ШЛА — диагноз не ставится.")
        return 2

    conn = читать(Path(a.conn), None, None)
    # Ряд резолвера необязателен: он заведён позже остальных,
    # и требовать его — значит ломать разбор старых окон.
    dns = читать(Path(a.dns), None, None) if Path(a.dns).is_file() else []
    эп = эпизоды(d, мед * ДОЛЯ_ПРОВАЛА)
    print(f"\nэпизодов зависания: {len(эп)}")
    if not эп:
        return 0

    вверх = [int(r["вверх_Б"]) for r in d]
    for x, y in эп:
        с, по = d[x]["время"], d[y]["время"]
        длит = в_сек(по) - в_сек(с) + 1
        окно = вверх[max(0, x - 10):x]
        пачка = max(окно) if окно else 0
        шлюз = [float(r["шлюз_мс"]) for r in d[x:y + 1]
                if r.get("шлюз_мс") not in ("-", "", None)]
        потери = sum(1 for r in d[x:y + 1] if r.get("шлюз_мс") == "-")

        # 🔴 ГЛАВНОЕ ЧИСЛО ЭПИЗОДА — ОДНОСТОРОННОСТЬ.
        # Если отдача во время эпизода держится, а приём рухнул, значит
        # машина слала, а обратно не шло: разрыв на ОБРАТНОМ пути, за
        # телефоном. Если упало и то и другое — это мы перестали слать
        # (игра встала сама, туннель умер, канал лёг целиком).
        # Замер 05.09.2026, эпизод 11:00:21: выход 13 068 Б/с при обычных
        # 15 498 (84 %), вход 4 117 при обычных 59 558 (7 %). Односторонне.
        фон_от = max(0, x - 20)
        фон_вх = [int(r["вниз_Б"]) for r in d[фон_от:x]]
        фон_исх = [int(r["вверх_Б"]) for r in d[фон_от:x]]
        эп_вх = [int(r["вниз_Б"]) for r in d[x:y + 1]]
        эп_исх = [int(r["вверх_Б"]) for r in d[x:y + 1]]

        print(f"\n─── {с} – {по}  ({длит} с) ───")
        if фон_вх and фон_исх:
            дв = st.median(эп_вх) / max(1, st.median(фон_вх))
            ди = st.median(эп_исх) / max(1, st.median(фон_исх))
            print(f"  приём:  {st.median(эп_вх):>8,.0f} Б/с — "
                  f"{дв * 100:>3.0f} % от фона")
            print(f"  отдача: {st.median(эп_исх):>8,.0f} Б/с — "
                  f"{ди * 100:>3.0f} % от фона")
            if ди > 0.5 and дв < 0.3:
                print("  🔴 ОДНОСТОРОННИЙ РАЗРЫВ: слали, обратно не шло — "
                      "рвётся ОБРАТНЫЙ путь")
            elif ди < 0.3 and дв < 0.3:
                print("  🟡 упало в обе стороны — перестали слать МЫ "
                      "(игра встала, туннель умер, канал лёг)")
                # 🔴 ЛОЖНЫЙ ЭПИЗОД. Обе стороны в нуле НЕСКОЛЬКО МИНУТ —
                # это чаще всего не поломка, а «игра не в матче»: конец
                # матча, экран загрузки, очередь. 05.09.2026 из пяти
                # найденных эпизодов ДВА оказались такими: 10:47:25 — сам
                # владелец перезапускал VPN (сказал об этом словами),
                # 09:52:11 — 341 секунда при 1–2 % в обе стороны.
                # Порог живости в `analyze_freeze.py` защищает ОКНО целиком
                # и не защищает эпизод внутри живого окна.
                # 🔴 ПОРОГ 60, а не 120 — уточнён по накопленным случаям.
                # За 05.09.2026 «обе стороны в нуле дольше минуты» случилось
                # ТРИ раза, и все три оказались НЕ поломкой: конец матча,
                # перезапуск VPN владельцем, снова конец матча. Настоящие
                # поломки того дня выглядели иначе — 32–59 с и односторонне,
                # а смерть туннеля держала отдачу на 43 %.
                # Порог 120 пропустил третий случай (109 с) молча.
                if длит > 60:
                    print(f"  🔴 И ЭТО ПОДОЗРИТЕЛЬНО: {длит} с в нуле "
                          f"в обе стороны.\n     Проверьте, шёл ли матч — "
                          f"конец матча и экран загрузки\n     выглядят "
                          f"ровно так же, а поломкой не являются.\n"
                          f"     Три таких случая за 05.09.2026 — ни одного "
                          f"настоящего.")
        print(f"  вахта за 10 с до: "
              f"{'🔴 пачка ' + format(пачка, ',') + ' Б' if пачка >= ПАЧКА else 'тихо (макс ' + format(пачка, ',') + ')'}")
        if шлюз:
            цел = "🟢 исправен" if потери == 0 and max(шлюз) < 50 else "🔴 страдал"
            print(f"  шлюз ВО ВРЕМЯ: медиана {st.median(шлюз):.2f} мс · "
                  f"макс {max(шлюз):.1f} · потеряно {потери}  {цел}")
        for строка in механизм(с, по, conn):
            print(f"  {строка}")
        # 🔴 Резолвер — отдельная статья: заминка DNS не видна ни
        # в пинге до шлюза, ни до сервера, оба идут по IP.
        # Печатается ТОЛЬКО если ряд перекрывает эпизод: пустой
        # перекрёсток надо называть пустым, а не молчать о нём.
        окно_dns = [r for r in dns
                    if в_сек(с) - ЗАПАС <= в_сек(r["время"]) <= в_сек(по) + ЗАПАС]
        if окно_dns:
            мс = [float(r["мс"]) for r in окно_dns]
            сбой = sum(1 for r in окно_dns if r["исход"] != "ok")
            print(f"  резолвер: медиана {st.median(мс):.0f} мс · "
                  f"макс {max(мс):.0f} · неудач {сбой} (проб {len(мс)})")
        elif dns:
            print("  резолвер: 🟡 ряд не перекрывает этот эпизод — "
                  "сказать нечего")

    print(f"\n🔴 Эпизодов {len(эп)}. Механизм у каждого свой, и по одному "
          f"случаю\n   на механизм нельзя сказать, какой из них частый "
          f"(`PIT-198`).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
