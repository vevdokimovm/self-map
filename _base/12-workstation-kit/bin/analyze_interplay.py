#!/usr/bin/env python3
"""Разбор ряда `interplay_probe.sh`: что с чем совпало и насколько.

🔴 ЗАЧЕМ ИНСТРУМЕНТ, А НЕ КОМАНДА НА СЛУЧАЙ. Разбор писался на коленке
четыре раза за утро 05.09.2026, и на четвёртый раз столбцы съехали:
`awk '$13>0'` под подписью «не в срок», тогда как тринадцатое поле —
`повторы`. Числа осмысленны, подпись неверна, отказ не падает
(`PIT-197`). Здесь обращение по ИМЕНИ заголовка — единственный способ,
и добавление столбца в сборщик ничего не ломает.

🔴 ЧЕГО ЭТОТ РАЗБОР НЕ ДЕЛАЕТ. Он не отвечает, есть ли связь. Он считает
совпадение и **сразу печатает, сколько за ним событий**: связь на трёх
событиях и связь на трёхстах выглядят одинаково, а стоят разного
(`PIT-198`). Решение о том, верить ли, принимает читающий.

Применение:
    analyze_interplay.py <rows.tsv> [--порог БАЙТ]
"""

import argparse
import statistics as st
from pathlib import Path

ПОРОГ_ВСПЛЕСКА = 1_000_000        # байт вверх за окно


def читать(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    строки = [l.rstrip("\n").split("\t") for l in path.read_text(encoding="utf-8").splitlines()]
    if not строки:
        raise SystemExit("файл пуст")
    шапка = строки[0]
    данные = [dict(zip(шапка, r)) for r in строки[1:] if len(r) == len(шапка)]
    if not данные:
        raise SystemExit("ни одной полной строки")
    return шапка, данные


def число(строка: dict[str, str], имя: str) -> int:
    try:
        return int(float(строка.get(имя, "0") or 0))
    except ValueError:
        return 0


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("файл", type=Path)
    p.add_argument("--порог", type=int, default=ПОРОГ_ВСПЛЕСКА,
                   help=f"байт вверх за окно, выше — всплеск (по умолчанию {ПОРОГ_ВСПЛЕСКА})")
    a = p.parse_args()

    шапка, данные = читать(a.файл)
    for нужен in ("время", "en0_вверх"):
        if нужен not in шапка:
            raise SystemExit(f"в шапке нет столбца «{нужен}» — это не ряд interplay_probe")

    вверх = [число(r, "en0_вверх") for r in данные]
    всплеск = [k for k, v in enumerate(вверх) if v >= a.порог]
    ровно = [k for k in range(len(вверх)) if k not in set(всплеск)]

    print(f"окон {len(данные)} · {данные[0]['время']} – {данные[-1]['время']}")
    print(f"всплесков (≥ {a.порог:,} Б за окно): {len(всплеск)} = "
          f"{100 * len(всплеск) // max(len(данные), 1)} % времени")
    print(f"отдано всего: {sum(вверх) / 1048576:.1f} МБ")
    if ровно:
        print(f"отдача ровная:   медиана {st.median([вверх[k] for k in ровно]):>10,.0f} Б/окно")
    if всплеск:
        print(f"отдача всплеск:  медиана {st.median([вверх[k] for k in всплеск]):>10,.0f} Б/окно")

    события = [c for c in ("повторы", "не_в_срок", "страниц_с_диска", "из_свопа") if c in шапка]
    if события:
        print(f"\n{'событие':<18}{'всего':>10}{'во всплесках':>14}{'в ровных':>10}"
              f"{'окон с ним':>12}")
    for имя in события:
        v = [число(r, имя) for r in данные]
        в_всп = sum(v[k] for k in всплеск)
        n = sum(1 for x in v if x)
        print(f"{имя:<18}{sum(v):>10}{в_всп:>14}{sum(v) - в_всп:>10}{n:>12}")
        if 0 < n <= 12:
            print(f"    🔴 событий всего {n} — это МАЛО. Любая доля ниже посчитана "
                  f"по ним и может развернуться на следующей выборке (PIT-198).")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
