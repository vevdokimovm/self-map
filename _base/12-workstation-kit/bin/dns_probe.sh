#!/bin/bash
# Ряд задержки резолвера — узкое место, найденное 05.09.2026 в системном логе.
#
# 🔴 ЗАЧЕМ. Туннель резолвит имя сервера на КАЖДОЕ соединение: 60 запросов
# `DNSServiceQueryRecord` за спокойную минуту, соединения живут 0.3–5 с.
# Заминка резолвера у оператора становится заминкой игры — и она НЕ ВИДНА
# ни в пинге до шлюза, ни в пинге до сервера, потому что оба идут по IP.
# Пока такого ряда не было, этот отказ был невидим по построению.
#
# 🔴 ЧТО ИМЕННО МЕРЯЕТ ЭТОТ РЯД — И ЧЕГО ОН НЕ МЕРЯЕТ.
# Проба берёт СЛУЧАЙНОЕ имя, то есть меряет резолвер МИМО кэша. Замер
# 05.09.2026 через хотспот: мимо кэша **185–536 мс**, из кэша **20 мс**.
# Туннель спрашивает одно и то же имя, значит почти всегда попадает в кэш
# и платит 20 мс, а полную цену — только когда истекает TTL записи.
#
# > Поэтому из этого ряда НЕЛЬЗЯ заключить «туннель тратит 300 мс тридцать
# > раз в минуту». Ряд отвечает на другой вопрос: сколько стоит промах
# > кэша, то есть насколько больно будет в момент истечения TTL.
# Величина, взятая не оттуда, — `PIT-197`, и здесь она поймана до вывода.

# 🔴 ИМЕНА ПЕРЕМЕННЫХ — ТОЛЬКО ЛАТИНИЦА (`PIT-202`). POSIX-shell разбирает
# `имя=1` как команду, а не как присваивание, и падает под nohup молча.
#
#   dns_probe.sh [секунд] [шаг]
set -u
DUR="${1:-3600}"
STEP="${2:-5}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/observations/dns-samples.tsv"
[ -s "$OUT" ] || printf 'время\tмс\tисход\n' > "$OUT"

end=$(( $(date +%s) + DUR ))
while [ "$(date +%s)" -lt "$end" ]; do
  # 🔴 Имя МЕНЯЕТСЯ на каждой пробе: закешированный ответ измеряет кэш,
  # а не резолвер, и ряд выйдет ровным независимо от состояния сети.
  name="p$(date +%s%N | tail -c 7).probe.example.com"
  t0=$(python3 -c 'import time; print(time.time())')
  if dscacheutil -q host -a name "$name" >/dev/null 2>&1; then
    res=ok
  else
    res=fail
  fi
  t1=$(python3 -c 'import time; print(time.time())')
  ms=$(python3 -c "print(f'{($t1-$t0)*1000:.1f}')")
  printf '%s\t%s\t%s\n' "$(date +%H:%M:%S)" "$ms" "$res" >> "$OUT"
  sleep "$STEP"
done
