#!/usr/bin/env python3
"""Разбор секундного ряда `freeze_watch.sh`: где связь пропадала.

🔴 ГЛАВНАЯ ЧАСТЬ — НЕ ПОИСК ПРОВАЛОВ, А ОТКАЗ ОТВЕЧАТЬ.
05.09.2026 разбор дал «провалов ноль» за четыре минуты и это выглядело
результатом опыта «вахта молчала». На деле в середине окна кончился матч,
входящий упал до 542 Б/с — и провалов не было **потому что нечему было
проваливаться**. Порог считался от медианы окна, медиана рухнула вместе
с трафиком, метод перестал различать что-либо.

> **Опыт с контролем над одной стороной проверяет ОБЕ стороны.**
> Убедиться, что молчал наблюдатель, недостаточно: надо убедиться, что
> наблюдаемое в это время делало то же, что и раньше.

Поэтому здесь есть **порог живости**: если медиана входящего ниже него,
инструмент **не считает провалы вообще** и говорит, что игра не шла.

Применение:
    analyze_freeze.py <freeze-watch.tsv> [--с ЧЧ:ММ:СС] [--по ЧЧ:ММ:СС]
"""

import argparse
import statistics as st
from pathlib import Path

ЖИВОСТЬ = 20_000      # Б/с медианы — ниже этого игра не идёт
ДОЛЯ_ПРОВАЛА = 0.15   # от медианы окна
ПАЧКА = 500_000       # Б/с отдачи — признак хода вахты


def читать(path: Path, с: str | None, по: str | None) -> list[dict[str, str]]:
    строки = [l.rstrip("\n").split("\t")
              for l in path.read_text(encoding="utf-8").splitlines()]
    if len(строки) < 2:
        raise SystemExit("в ряду меньше двух строк")
    шапка = строки[0]
    d = [dict(zip(шапка, r)) for r in строки[1:] if len(r) == len(шапка)]
    if с:
        d = [r for r in d if r["время"] >= с]
    if по:
        d = [r for r in d if r["время"] <= по]
    return d


def _в_секунды(t: str) -> int:
    """ЧЧ:ММ:СС в секунды от полуночи — для разностей между соседями."""
    ч, м, с = (int(x) for x in t.split(":"))
    return ч * 3600 + м * 60 + с


def события(d: list[dict], порог: float) -> list[tuple[int, int]]:
    """Подряд идущие плохие секунды — одно событие, а не пять."""
    итог, тек = [], None
    for k, r in enumerate(d):
        плохо = int(r["вниз_Б"]) < порог
        if плохо and тек is None:
            тек = [k, k]
        elif плохо:
            тек[1] = k
        elif тек is not None:
            итог.append(tuple(тек))
            тек = None
    if тек:
        итог.append(tuple(тек))
    return итог


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("файл", type=Path)
    p.add_argument("--с", dest="с")
    p.add_argument("--по", dest="по")
    p.add_argument("--живость", type=int, default=ЖИВОСТЬ)
    a = p.parse_args()

    d = читать(a.файл, a.с, a.по)
    if not d:
        raise SystemExit("в окне нет замеров")
    вниз = [int(r["вниз_Б"]) for r in d]
    вверх = [int(r["вверх_Б"]) for r in d]
    мед = st.median(вниз)

    print(f"окно {d[0]['время']} – {d[-1]['время']}, {len(d)} секунд")
    print(f"медиана входящего: {мед:,.0f} Б/с")

    # 🔴 РЯД МОГ КОНЧИТЬСЯ РАНЬШЕ, ЧЕМ ЗАКАЗАННОЕ ОКНО.
    # `freeze_watch.sh` живёт заданное число секунд и умирает МОЛЧА.
    # 05.09.2026 он кончился в 10:24:40, разбор заказали по 10:30:11 —
    # и заголовок напечатал «74 секунды» как ни в чём не бывало.
    # Шесть минут игры остались неизмеренными, и узналось это случайно.
    # Тот же класс, что `PIT-200`: подпись не совпадает с измеренным.
    if a.по and d[-1]["время"] < a.по:
        print(f"\n🔴 РЯД КОНЧИЛСЯ РАНЬШЕ ОКНА: заказано по {a.по}, "
              f"последний замер {d[-1]['время']}.")
        print("   Сборщик умер или не запускался. Пропуск НЕ означает "
              "«провалов не было» —")
        print("   в это время не было НАБЛЮДЕНИЯ. Перезапустите "
              "freeze_watch.sh и не считайте\n   этот кусок за тихий.")
    # 🔴 И ДЫРА ВНУТРИ РЯДА — она опаснее обрезки по краям.
    # Сборщик можно перезапустить, и файл склеится встык: две части
    # соседними строками, между ними шесть минут без наблюдения. Ряд
    # выглядит сплошным, длина окна печатается верная, а провал в дыре
    # не виден по построению. Проверяется по РАЗНОСТИ ВРЕМЕНИ соседних
    # строк, а не по их числу.
    дыры = []
    for i in range(1, len(d)):
        было, стало = _в_секунды(d[i - 1]["время"]), _в_секунды(d[i]["время"])
        if стало - было > 5:
            дыры.append((d[i - 1]["время"], d[i]["время"], стало - было))
    if дыры:
        всего = sum(x[2] for x in дыры)
        слово = "ДЫРА" if len(дыры) % 10 == 1 and len(дыры) % 100 != 11 else "ДЫР"
        print(f"\n🔴 В РЯДУ {len(дыры)} {слово}, всего {всего} с без наблюдения:")
        for нач, кон, дл in дыры[:5]:
            print(f"   {нач} → {кон}  ({дл} с)")
        print("   Ряд склеен встык и выглядит сплошным. Провал внутри дыры")
        print("   не виден по построению — не считать это время тихим.")

    if a.с and d[0]["время"] > a.с:
        print(f"\n🔴 РЯД НАЧАЛСЯ ПОЗЖЕ ОКНА: заказано с {a.с}, "
              f"первый замер {d[0]['время']}.")

    # 🔴 ОТКАЗ ОТВЕЧАТЬ — до всякого счёта
    if мед < a.живость:
        print(f"\n🔴 ИГРА В ЭТОМ ОКНЕ НЕ ШЛА (медиана ниже порога живости "
              f"{a.живость:,} Б/с).")
        print("   Провалы НЕ считаются: их отсутствие ничего не значило бы —")
        print("   нечему проваливаться. Возьмите окно, где игра работала.")
        return 2

    порог = мед * ДОЛЯ_ПРОВАЛА
    соб = события(d, порог)
    print(f"порог провала: {порог:,.0f} Б/с")
    print(f"\n🔴 событий провала: {len(соб)}")
    if соб:
        print(f"{'начало':<10}{'длит,с':>8}{'пачка вахты за 10 с ДО':>26}")
    с_пачкой = 0
    for x, y in соб:
        окно = вверх[max(0, x - 10):x]
        была = max(окно) if окно else 0
        if была >= ПАЧКА:
            с_пачкой += 1
        метка = f"🔴 {была:,} Б" if была >= ПАЧКА else f"нет (макс {была:,})"
        # 🔴 ДЛИТЕЛЬНОСТЬ — ПО ВРЕМЕНИ, А НЕ ПО ЧИСЛУ СТРОК.
        # Ряд назван секундным, и это правда лишь по медиане: 21 %
        # шагов выходят по 2 с (пинг ждёт таймаута), среднее 1.22 с.
        # Счёт строками занижал длительности на четверть.
        длит = _в_секунды(d[y]["время"]) - _в_секунды(d[x]["время"]) + 1
        print(f"{d[x]['время']:<10}{длит:>8}  {метка:>24}")
    if соб:
        print(f"\nсобытий с пачкой вахты перед ними: {с_пачкой} из {len(соб)}")
        if len(соб) < 10:
            print(f"🔴 событий {len(соб)} — МАЛО. Доля выше посчитана по ним "
                  f"и может развернуться на следующей выборке.")

    # 🔴 СГУЩЁННОСТЬ. 05.09.2026 разбор напечатал «событий провала: 17»,
    # и все семнадцать легли в 154 секунды подряд с медианой входящего
    # 2 563 Б/с. Это ОДИН обрыв на три минуты, который дробилка событий
    # разрезала на семнадцать кусков по случайным мигам выше порога.
    # Семнадцать независимых событий и один трёхминутный обрыв — разные
    # диагнозы, а число одно и то же.
    if len(соб) >= 3:
        # 🔴 по ВРЕМЕНИ. Прежняя редакция брала разность индексов,
        # считая шаг ровно секундой; он 1.22 с в среднем.
        размах = (_в_секунды(d[соб[-1][1]]["время"])
                  - _в_секунды(d[соб[0][0]]["время"]) + 1)
        плотность = len(соб) / max(1, размах)
        if плотность > 0.05:
            print(f"\n🔴 {len(соб)} событий уместились в {размах} с — это НЕ "
                  f"{len(соб)} событий,\n   а один эпизод, разрезанный мигами "
                  f"выше порога. Считать их\n   независимыми нельзя: выборка "
                  f"здесь размером в ОДИН случай.")

    # 🔴 ЛОКАЛЬНЫЙ КОНЕЦ СЧИТАЕТСЯ ОТДЕЛЬНО ВНУТРИ СОБЫТИЙ И ВНЕ ИХ.
    # Прежняя редакция брала максимум по ВСЕМУ окну и печатала «локальный
    # конец тоже страдал». 05.09.2026 это оказалось ложью ровно наоборот:
    # во время обрыва шлюз отвечал за 3.46 мс без единой потери, а 428 мс
    # и две потерянные пробы случились ВНЕ обрыва, в здоровое время.
    # Величина была взята не оттуда (`PIT-197`), и вывод получился обратный.
    плохие = set()
    for x, y in соб:
        плохие.update(range(x, y + 1))

    def свод_шлюза(имя: str, ряд: list) -> None:
        знач = [float(r["шлюз_мс"]) for r in ряд
                if r.get("шлюз_мс") not in ("-", "", None)]
        проп = sum(1 for r in ряд if r.get("шлюз_мс") == "-")
        if not знач:
            print(f"  {имя:<22} проб нет")
            return
        цел = "🟢 исправен" if проп == 0 and max(знач) < 50 else "🔴 страдал"
        print(f"  {имя:<22} медиана {st.median(знач):>6.2f} мс · "
              f"макс {max(знач):>6.1f} · потеряно {проп:>2}  {цел}")

    print("\nдо шлюза (локальный конец — Wi-Fi и телефон):")
    if плохие:
        свод_шлюза("ВО ВРЕМЯ провалов", [r for i, r in enumerate(d) if i in плохие])
        свод_шлюза("вне провалов", [r for i, r in enumerate(d) if i not in плохие])
        print("\n  🔴 Читать надо ПЕРВУЮ строку. Если во время провалов шлюз "
              "исправен,\n     а страдал вне их — разрыв ЗА телефоном, "
              "и Wi-Fi тут ни при чём.")
    else:
        свод_шлюза("всё окно", d)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
