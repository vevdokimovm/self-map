#!/bin/zsh
# =============================================================================
# push_archives.sh — прицепить готовые portrait-of-taste-v*.zip как GitHub Releases.
#
# Описания релизов ЗАШИТЫ в этот скрипт — не зависит от CHANGELOG в архиве.
#
# ИДЕМПОТЕНТНО: уже опубликованный релиз (не draft) — НЕ трогается повторными
# прогонами, ни описание, ни ассет не перезаливаются. Раньше был баг: скрипт
# перезаливал 560 МБ на каждый запуск даже когда всё уже готово. Теперь —
# только draft публикуется/довершается, готовое пропускается молча.
#
# ЗАПУСК:
#   zsh ~/Downloads/push_archives.sh
#   zsh ~/Downloads/push_archives.sh ~/Downloads
#   DRY=1 zsh ~/Downloads/push_archives.sh              # план без публикации
#   FORCE=1 zsh ~/Downloads/push_archives.sh            # обновить ВСЁ (описания + перезалить ассеты)
#   NOTES_ONLY=1 zsh ~/Downloads/push_archives.sh        # только описания, ассеты не трогать (быстро)
# =============================================================================

# Явные пути к утилитам (защита от битого PATH в оболочке)
DU=/usr/bin/du
CUT=/usr/bin/cut
BASENAME=/usr/bin/basename
DIRNAME=/usr/bin/dirname
SORT=/usr/bin/sort
MKTEMP=/usr/bin/mktemp
BASE64=/usr/bin/base64
TR=/usr/bin/tr
AWK=/usr/bin/awk
SED=/usr/bin/sed
HEAD=/usr/bin/head
RM=/bin/rm
CAT=/bin/cat
SLEEP=/bin/sleep

# gh обычно в /opt/homebrew/bin (M-series) или /usr/local/bin (Intel)
if [ -x /opt/homebrew/bin/gh ]; then
    GH=/opt/homebrew/bin/gh
elif [ -x /usr/local/bin/gh ]; then
    GH=/usr/local/bin/gh
else
    # последняя попытка — через PATH
    export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:${PATH:-}"
    GH=$(command -v gh 2>/dev/null)
fi

# Проверки
[ -x "$GH" ] || { print -P "%F{red}❌ gh не найден. brew install gh && gh auth login%f"; exit 1; }
for tool in "$DU" "$CUT" "$BASENAME" "$SORT" "$MKTEMP" "$AWK" "$SED" "$HEAD"; do
    [ -x "$tool" ] || { print -P "%F{red}❌ утилита не найдена: $tool%f"; exit 1; }
done

set -u

OWNER="${OWNER:-vevdokimovm}"
REPO="${REPO:-portrait-of-taste}"
DIR="${1:-${DIR:-$HOME/Downloads}}"
DRY="${DRY:-0}"

red(){ print -P "%F{red}$*%f"; }
grn(){ print -P "%F{green}$*%f"; }
ylw(){ print -P "%F{yellow}$*%f"; }
cyn(){ print -P "%F{cyan}$*%f"; }
bld(){ print -P "%B$*%b"; }
die(){ red "❌ $*"; exit 1; }

$GH auth status >/dev/null 2>&1 || die "gh не авторизован. gh auth login"
[ -d "$DIR" ] || die "папка не найдена: $DIR"
$GH repo view "$OWNER/$REPO" >/dev/null 2>&1 || die "репа $OWNER/$REPO не найдена"

