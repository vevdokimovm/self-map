#!/bin/bash
# PreToolUse (Edit/Write/MultiEdit) — запрет правки файлов внутри `_base/` любой репы.
#
# ЗАЧЕМ. `_base/` — зеркало канона base-repo, разложенное `sync-base.sh`/
# `sync_base_local.py` (`00-infrastructure/78-base-embedding.md`). Каждый файл там несёт
# собственную шапку «DO-NOT-EDIT»: «Правки здесь будут затёрты при следующей раздаче» —
# но текстовый запрет агент обходит рассуждением, хук — нет (урок Replit, июль 2025,
# `69-agents-hooks-and-gates.md` §4а). По `69` §4: «нарушение возможно и цена высока →
# хук», не инструкция.
#
# ЖИВОЙ ПРЕЦЕДЕНТ. `PIT-147` (26.08.2026): правка внутри `_base/`-подобной структуры
# самой base-repo привела к порче корня канона — ровно тот класс ошибки, для которого
# `_base/` как пространство создавалось изолированным. Хук не предотвратил бы САМ PIT-147
# (там пострадал корень канона, не чужой `_base/`), но закрывает симметричный риск:
# правку ВНУТРИ уже розданного зеркала, которая молча исчезнет при следующей раздаче.
#
# ГРАНИЦА. Ловит только путь вида `.../_base/...` — не мнение о том, хорошая ли правка.
set -uo pipefail

input=$(cat)
path=$(printf '%s' "$input" | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)  # непонятный вход хуку такого типа не блокировать — не наша зона
ti = data.get("tool_input", {})
p = ti.get("file_path") or ti.get("path") or ""
print(p)
' 2>/dev/null) || exit 0

[ -z "$path" ] && exit 0

case "$path" in
  */_base/*|_base/*)
    echo "Заблокировано: правка внутри _base/ — это чужое зеркало канона, не оригинал." >&2
    echo "Путь: $path" >&2
    echo "Правится только оригинал (base-repo), локальные правила репы — рядом," >&2
    echo "в 00-infrastructure/ на уровень выше _base/. Следующая раздача сотрёт эту правку." >&2
    exit 2
    ;;
esac
exit 0
