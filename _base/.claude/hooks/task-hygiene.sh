#!/usr/bin/env bash
# task-hygiene.sh — закрытое не должно оставаться в рабочих файлах задач.
#
# Версия: 1.0.0 (2026-08-28)
#
# ЗАКАЗ ВЛАДЕЛЬЦА 28.08.2026, дословно:
#   «сделай тоже хуки, гейты, автоматический механизм про то, что когда задача
#    в планировщике или в других репах роадмапа/тасок выполняется — то она
#    проставляется выполненной и выносится в логи. чтобы файлы всех тасок
#    оставались актуальными»
#
# ЧТО ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ — граница названа вслух (`71` §7г-бис).
#   Делает:    считает закрытое в рабочих файлах и говорит, когда его слишком
#              много; печатает конкретные файлы и числа.
#   НЕ делает: не переносит пункты сам. Перенос требует суждения — в какой
#              приёмник, с какой формулировкой, что сохранить, — а инструмент,
#              притворяющийся, что решает это, был бы хуже отсутствующего.
#
# ПОЧЕМУ НЕ БЛОКИРУЕТ. Закрытый пункт в файле — не дефект в момент закрытия:
# он там оказывается законно, отметиться надо где-то. Дефект — когда он там
# ЖИВЁТ. Поэтому порог, а не запрет: один-два — норма рабочего дня, десяток —
# файл перестают читать.
#
# ЗАМЕР, ИЗ КОТОРОГО ВЗЯТ ПОРОГ (28.08.2026, `mission-control`):
#   было 1348 строк в четырёх рабочих файлах, больше половины — закрытое;
#   ROADMAP.md держал 47 закрытых пунктов против 8 открытых, то есть нарушал
#   собственное правило шапки. После чистки — 692 строки.
#   Порог 5 выбран так, чтобы поймать накопление задолго до этого состояния.

set -Eeuo pipefail

THRESHOLD="${TASK_HYGIENE_THRESHOLD:-5}"
ROOT="${CLAUDE_PROJECT_DIR:-$PWD}"

# Файл → куда уезжает закрытое (`22-file-map.md` §4)
check_file() {
  local rel sink path
  rel="$1"; sink="$2"; path="$ROOT/$rel"
  [ -f "$path" ] || return 0

  # `- [x]` и зачёркнутые строки таблиц `| ~~…~~ |`
  local done_boxes done_strikes total
  done_boxes="$(grep -cE '^[[:space:]]*[-*][[:space:]]*\[x\]' "$path" 2>/dev/null || true)"
  done_strikes="$(grep -cE '^\|[^|]*~~' "$path" 2>/dev/null || true)"
  total=$(( ${done_boxes:-0} + ${done_strikes:-0} ))

  if [ "$total" -ge "$THRESHOLD" ]; then
    echo "  · ${rel}: закрытого внутри — ${total} (порог ${THRESHOLD}) → ${sink}"
    return 1
  fi
  return 0
}

found=0
check_file "ROADMAP.md" "ROADMAP_HISTORY.md"                  || found=1
check_file "TASKS.md"   "TASKS_HISTORY.md (с датой)"          || found=1
check_file "BACKLOG.md" "reports/tasks-completed-log.md"      || found=1
check_file "BOARD.md"   "reports/tasks-completed-log.md"      || found=1

if [ "$found" -eq 1 ]; then
  echo ""
  echo "🧹 ГИГИЕНА ЗАДАЧ: в рабочих файлах накопилось закрытое (см. выше)."
  echo "   Правило владельца 28.08.2026: «чисть выполненные в логи, не оставляй"
  echo "   их внутри — чтобы служебки были актуальными и я понимал проще состояние»."
  echo "   Перенести с указанием, ГДЕ именно закрыт пункт (репа + версия), и удалить"
  echo "   из рабочего файла. Порядок и приёмники — 22-file-map.md §4."
fi

# Всегда 0: это информирование, не гейт. Блокировать закрытие батча из-за
# гигиены значило бы останавливать работу ради опрятности — цена ошибки
# несоразмерна (`STOP_CONDITIONS`: жёстко стопят три класса, этого среди них нет).
exit 0
