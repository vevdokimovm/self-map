from gtts import gTTS

# Текст молитвы
prayer_text = """
Я человек. Не герой. И в этом - моя сила.
Господи, я благодарю Тебя за то, что я есть.
За то, что я живу, дышу, чувствую, сомневаюсь.
За то, что я не идеален - и это значит, что я реален.
Я отказываюсь от мифа, что должен быть кем-то особенным.

Позволь мне быть просто собой.
Позволь ошибаться, уставать, падать и вставать.
Позволь идти медленно, но с верой.
Позволь быть обычным, но не пустым.

Пусть мои шаги будут не для восхищения других, 
а для приближения к Истине.
Пусть я не буду жить ради аплодисментов,
а ради любви, добра, тихого света в душе.

Научи меня радоваться прогрессу, а не совершенству.
Научи принимать свои слабости - 
как часть Твоего замысла, как путь роста.
Научи смотреть на себя с милостью,
а не с гневом и требовательностью.

Я отпускаю образ идеального героя,
и принимаю себя - человека.
Уязвимого. Настоящего. Достойного любви.
Во имя Жизни, смысла и эволюции.

Аминь.
"""


# Озвучка
tts = gTTS(text=prayer_text, lang='ru')

# Сохранение в mp3-файл
tts.save("молитва_простого_человека.mp3")

print("Готово! Файл сохранён как 'молитва_простого_человека.mp3'")